const run = () => auditExamPaper([...BODY, ...ANSWER].join('\n'), {
  subject: '数学', stage: 'primary_mid', genType: 'exam',
}).html;

const bodyOf = (h) => h.split(/<h2[^>]*>\s*参考答案/)[0];
const heads = (h) => [...h.matchAll(/<h[2-4]>([\s\S]*?)<\/h[2-4]>/g)].map((m) => m[1].trim());
const pTexts = (h) => [...h.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)]
  .map((m) => m[1].replace(/<[^>]+>/g, '').replace(/&emsp;|&nbsp;/g, ' ').trim())
  .filter(Boolean);

describe('混合整卷：一张卷里六种形态同时成立（不是逐条判据）', () => {
  const out = run();
  const hs = heads(out);
  const find = (prefix) => hs.filter((t) => t.startsWith(prefix));

  it('一/二（并列算式）不得长出题号、标题保持单价、内容原样', () => {
    // 题号只能出现在三/四/五/六 的带号题上；一/二 的算式行不得以数字开头（只看正文，答案区另有号）
    const body = bodyOf(out);
    const numbered = pTexts(body).filter((t) => /^\d{1,2}\s*[.、．]/.test(t));
    expect(numbered.length, '正文带号题＝6+3+4+2＝15').toBe(15);
    for (const t of ['3×5＝', '6×2＋6', '34＋25＝', '45＋38']) {
      const line = pTexts(body).find((x) => x.includes(t));
      expect(line, `${t} 所在行不得带题号`).toBeTruthy();
      expect(/^\d{1,2}\s*[.、．]/.test(line), `${t} 行不得被编号`).toBe(false);
    }
    expect(find('一、')[0], '一 的标题保持单价').toBe('一、直接写得数（每题1分，共14分）');
    expect(find('二、')[0], '二 的标题保持单价').toBe('二、用竖式计算（每题3分，共12分）');
  });

  it('三（填一填）：标题合成为真题写法，且逐题标分一条不丢', () => {
    expect(find('三、')[0], '正文标题').toBe('三、填一填（每题4分，共24分）');
    const items = pTexts(bodyOf(out)).filter((t) => /^\d{1,2}\s*[.、．]/.test(t) && /（每空1分，共4分）$/.test(t));
    expect(items.length, '6 道题逐题标分须全在').toBe(6);
  });

  it('四/五（同档）与六（多档）各自合成为正确形态', () => {
    expect(find('四、')[0], '同档：每题X分').toBe('四、判断（每题2分，共6分）');
    expect(find('五、')[0], '同档：每题X分').toBe('五、选择（每题2分，共8分）');
    expect(find('六、')[0], '多档：分组式').toBe('六、解决问题（第1小题4分，第2小题6分，共10分）');
  });

  it('答案区同名大题标题镜像同一括注（一/二 不动）', () => {
    for (const p of ['三、', '四、', '五、', '六、']) {
      const both = find(p);
      expect(both.length, `${p} 正文＋答案区各一处`).toBe(2);
      expect(both[1], `${p} 答案区须镜像`).toBe(both[0]);
    }
    for (const p of ['一、', '二、']) {
      const both = find(p);
      expect(both.length).toBe(2);
      expect(both[1], `${p} 答案区不得被改`).toBe(both[0]);
    }
  });

  it('全卷分值账：各大题标题分之和＝14+12+24+6+8+10', () => {
    const bodyHeads = hs.slice(0, 6);
    const totals = bodyHeads.map((t) => Number((t.match(/共\s*(\d+)\s*分/) || [])[1]));
    expect(totals).toEqual([14, 12, 24, 6, 8, 10]);
    expect(totals.reduce((a, b) => a + b, 0)).toBe(74);
  });

  it('内容不丢：六道大题的题干关键串全部在位', () => {
    for (const t of ['4个3相加', '5×3＝', '在○里填', '一支铅笔2元', '得数是12', '3×4与4×3', '得数最大',
      '5×4表示', '3×6', '每盒有6个鸡蛋', '练习本']) {
      expect(out, `缺内容：${t}`).toContain(t);
    }
  });
});

describe('混合实发：三步流程齐备且有序；编号口径不得与“动作相同也编号”并存', () => {
  const t = getPromptTemplate({ grade: 'primary_mid', subject: '数学', genType: 'exam' }).template;

  it('三步按 ①→②→③ 的顺序出现（不是两支二选一）', () => {
    const i1 = t.indexOf('第①步');
    const i2 = t.indexOf('第②步');
    const i3 = t.indexOf('第③步');
    expect(i1, '缺第①步').toBeGreaterThan(-1);
    expect(i2, '缺第②步').toBeGreaterThan(i1);
    expect(i3, '缺第③步').toBeGreaterThan(i2);
    expect(t, '旧“两支”并列写法不得回潮').not.toContain('两支的判法');
  });

  it('第③步的两态都写了“按①写出来的内容算”，标题分值不是先定的', () => {
    expect(t).toContain('最后回到大题标题标分');
    expect(t).toContain('大题下面有子题');
    expect(t).toContain('大题下面没有子题');
    expect(t).toContain('不得先定分数去凑内容');
  });

  it('编号口径：并列同类作答项不编号，且不得与“动作相同也编号”并存', () => {
    expect(QUESTION_OBJECT_CALIBER).toMatch(/并列的同类作答项/);
    expect(QUESTION_OBJECT_CALIBER).toMatch(/其下不编号/);
    expect(QUESTION_OBJECT_CALIBER, '相反半句不得回潮').not.toMatch(/即使作答动作相同也各自编号/);
  });

  it('排版条把“算式”归入一道题内的并列小项（与编号口径同向）', () => {
    expect(t).toContain('算式');
    expect(t).toMatch(/多组并列小项（多组词／待填位／选项／算式）/);
    expect(t).toContain('不因分行成为多道题、不各自编号');
  });

  it('跨学段×学科混合扫描：三步有序、无相反半句、并列项含算式', () => {
    const bad = [];
    for (const stage of ['primary_low', 'primary_mid', 'middle', 'high']) {
      for (const subject of ['语文', '数学', '英语']) {
        const tt = getPromptTemplate({ grade: stage, subject, genType: 'exam' }).template;
        const i1 = tt.indexOf('第①步');
        const i2 = tt.indexOf('第②步');
        const i3 = tt.indexOf('第③步');
        const tag = `${stage}|${subject}`;
        if (!(i1 > -1 && i2 > i1 && i3 > i2)) bad.push(`${tag}：三步不成序`);
        if (tt.includes('两支的判法')) bad.push(`${tag}：旧“两支”写法回潮`);
        if (tt.includes('即使作答动作相同也各自编号')) bad.push(`${tag}：相反半句回潮`);
        if (!/多组并列小项（多组词／待填位／选项／算式）/.test(tt)) bad.push(`${tag}：并列项缺“算式”`);
        if (!tt.includes('不因分行成为多道题、不各自编号')) bad.push(`${tag}：缺“不因分行成为多道题”`);
        if (!tt.includes('0段没有小题号')) bad.push(`${tag}：缺“0段没有小题号”`);
      }
    }
    expect(bad, '跨学段混合扫描').toEqual([]);
  });
});
