  '<p>5. 文具店里一支铅笔2元，买5支铅笔一共要____元。（每空1分，共4分）</p>',
  '<p>6. 得数是12的乘法算式有____和____，它们的积都是____，口诀是____。（每空1分，共4分）</p>',
  // 四、判断：3 道带号题，每道 2 分
  '<h3>四、判断（共6分）</h3>',
  '<p>1. 3×4与4×3的得数相同。（2分）</p>',
  '<p>2. 两个数相乘，交换位置得数不变。（2分）</p>',
