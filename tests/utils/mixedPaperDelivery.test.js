// ============================================================
// 混合整卷验收（2026-10-21 属主：**不要一个个判据单独测，混合测**）
// ------------------------------------------------------------
// 目的：单个判据各自为真、合起来互相拆台——本文件把**一张卷里同时出现**的形态放在一起跑，
//   验的是“同一份实发/同一份产物”的不变量，而不是某条判据单独成立。
//
// 覆盖（同一张卷）：
//   一 口算（并列算式、无题号、标题单价）      → B 不得加号、不得改标题、不得补标分
//   二 竖式（同上）                          → 同上
//   三 填一填（6 道带号题、逐题（每空1分，共N分）、合计 24） → 标题合成为（每题4分，共24分）、逐题标分保留
//   四 判断（3 道带号题、每道（2分）、合计 6）   → 合成为（每题2分，共6分）
//   五 选择（4 道带号题、每道（2分）、合计 8）   → 合成为（每题2分，共8分）
//   六 解决问题（2 道带号题、总分不同 4/6）      → 多档分组式
//   答案区：三/四/五/六 同名大题标题须镜像同一括注；一/二 不动
//   A 侧：三步流程齐备且有序；编号对象口径不得与“动作相同也编号”并存
// ============================================================
