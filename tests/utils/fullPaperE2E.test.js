// 整卷端到端（2026-10-19 属主："真端到端测试／大类名分学段的位置还在吗"）
// ============================================================
// 做法：按 A 侧规则构造**整份**试卷（不是片段）→ 走完整 auditExamPaper（B＋全部校验）→ 断言终态。
// 覆盖两种学段的大类名设计：
//   小学：大类（部分）层在大题之上（<h2>，自带序号+总分），其下才是大题（<h3>）；
//         B 不得把大类层当大题来合成（它下面到下一个标题之间没有"题"）。
//   中学：不设大类层；域型名直接作大题标题（只作范围标识）——B **不得**给它加单价。
// ⚠️ 边界：模型生成 A 的那一步无法本地跑（无本地推理入口）；本件验"给定 A 合规产物，整条程序链不改坏"。
// ============================================================
import { describe, it, expect } from 'vitest';
import { auditExamPaper } from '../../src/utils/examValidator.js';

const run = (html, stage) => auditExamPaper(html, { subject: '数学', stage, genType: 'exam' }).html;
const allH = (html) => [...html.matchAll(/<h[2-4]>([\s\S]*?)<\/h[2-4]>/g)].map((m) => m[1]);
const h3 = (html) => [...html.matchAll(/<h3>([\s\S]*?)<\/h3>/g)].map((m) => m[1]);
const h2 = (html) => [...html.matchAll(/<h2>([\s\S]*?)<\/h2>/g)].map((m) => m[1]);
const count = (html, re) => (html.match(re) || []).length;

/** 小学整卷：大类层（2 层）＋ 7 个大题，总分 56+44=100 */
const PRIMARY = [
  '<h1>阶段测评</h1>',
  '<h2>第一部分 数与代数（共56分）</h2>',
  // 一、口算：无题号、无要求行（A2）
  '<h3>一、直接写出得数（每式1分，共20分）</h3>',
  '<p>4×2＝____　5×3＝____　2×6＝____　3×3＝____</p>',
  '<p>6×6＝____　4×5＝____　1×5＝____　3×6＝____</p>',
  '<p>5×5＝____　2×2＝____　4×4＝____　6×3＝____</p>',
  '<p>5×4＝____　3×2＝____　6×2＝____　2×3＝____</p>',
  '<p>3×6＝____　4×4＝____　5×2＝____　6×6＝____</p>',
  // 二、竖式：无题号、无要求行（A2）
  '<h3>二、列竖式计算（每式3分，共12分）</h3>',
  '<p>34＋25＝____　48－16＝____</p>',
  '<p>27＋35＝____　63－28＝____</p>',
  // 三、填空：有题号，每题后标分（A1）→ B 应合成分组式
  '<h3>三、填空（共24分）</h3>',
  '<p>3. 4个3相加，写成乘法算式是____，读作____。（6分）</p>',
  '<p>4. 把口诀补充完整。（每空1分，共4分）</p>',
  '<p>5. 在○里填上“＞”“＜”或“＝”。（每题1分，共6分）</p>',
  '<p>6. 文具店里一盒橡皮有6块。（每空1分，共4分）</p>',
  '<p>7. 在括号里填上合适的数。（每空1分，共4分）</p>',
  '<h2>第二部分 综合运用（共44分）</h2>',
  // 四、判断：有题号，每题（2分）→ B 应合成"每题2分"
  '<h3>四、判断下面各题，对的画“√”，错的画“×”（共10分）</h3>',
  '<p>8. 8×3＝24，读作八乘三等于二十四。（2分）</p>',
  '<p>9. 3个6相加可以写成6×3。（2分）</p>',
  '<p>10. 5×5＝25，口诀是五五二十五。（2分）</p>',
  '<p>11. 4×2＝8，4是乘数，2是被乘数。（2分）</p>',
  '<p>12. 6×1＝6。（2分）</p>',
  // 五、选择：有题号，每题（2分）
  '<h3>五、选择正确答案的序号填在括号里（共10分）</h3>',
  '<p>13. 下面算式中，表示“3个6相加”的是（　）（2分）</p>',
  '<p>14. 与“四六二十四”对应的算式是（　）（2分）</p>',
  '<p>15. 每盘放5个苹果，4盘一共多少个？列式正确的是（　）（2分）</p>',
  '<p>16. 得数最大的是（　）（2分）</p>',
  '<p>17. 一支笔3元，买6支一共要多少元？正确想法是（　）（2分）</p>',
  // 六、解决问题：有题号、每处同价
  '<h3>六、解决问题：列式并计算，写出答语（共16分）</h3>',
  '<p>18. 每盒有6支笔，3盒一共多少支？（每处2分，共6分）</p>',
  '<p>19. 有24个苹果，平均放在4个盘子里，每盘几个？（每处2分，共6分）</p>',
  '<p>20. 小明买了5本本子，每本3元，一共花了多少元？（每处2分，共4分）</p>',
  // 七、写话：无题号、单判分处（A2）
  '<h3>七、看图写话：仔细观察图片，写几句话（共8分）</h3>',
  '<p>图上的小朋友在做什么？</p>',
].join('\n');

describe('整卷端到端 · 小学（大类层在大题之上）', () => {
  const out = run(PRIMARY, 'primary_mid');
  console.log('[E2E 小学]', JSON.stringify({ 大类层: h2(out), 大题: h3(out) }));

  it('大类层（部分层）原样保留，不被当大题合成', () => {
    expect(h2(out)).toContain('第一部分 数与代数（共56分）');
    expect(h2(out)).toContain('第二部分 综合运用（共44分）');
  });

  it('无题号大题：标题带单价、其下没有重复要求行', () => {
    expect(h3(out)).toContain('一、直接写出得数（每式1分，共20分）');
    expect(h3(out)).toContain('二、列竖式计算（每式3分，共12分）');
    expect(out, '不得出现"直接写出得数"的重复题干行').not.toMatch(/<p[^>]*>\s*1\.\s*直接写出得数/);
    expect(out, '不得出现"列竖式计算"的重复题干行').not.toMatch(/<p[^>]*>\s*2\.\s*列竖式计算/);
  });

  it('填空（题号层）：标题合成分组式，逐题标注全保留', () => {
    expect(h3(out)).toContain('三、填空（第3、5小题各6分，第4、6、7小题各4分，共24分）');
    expect(out, '第3题（6分）保留').toContain('（6分）');
    expect(out, '第5题（每题1分，共6分）保留').toContain('（每题1分，共6分）');
    expect(count(out, /每空1分，共4分/g), '第4/6/7题的标注').toBe(3);
  });

  it('判断/选择（题号层）：标题合成"每题X分"，逐题（2分）全保留', () => {
    expect(h3(out)).toContain('四、判断下面各题，对的画“√”，错的画“×”（每题2分，共10分）');
    expect(h3(out)).toContain('五、选择正确答案的序号填在括号里（每题2分，共10分）');
    expect(count(out, /（2分）/g), '判断5＋选择5').toBe(10);
  });

  // 🔴 2026-10-20（属主纠正）：B 合成**按题的总分**，不按"空/处"——同单位同单价但每题总分不同时，
  //   也不得写成"每处2分"（题内处数不同 ⇒ 该单价撑不起标题），要按每题总分分组。
  it('解决问题：每题总分不同 → 标题按题的总分分组（第18、19小题各6分，第20小题4分）', () => {
    expect(h3(out)).toContain('六、解决问题：列式并计算，写出答语（第18、19小题各6分，第20小题4分，共16分）');
    expect(count(out, /每处2分，共\d+分/g), '题内 3 条标注保留').toBe(3);
  });

  it('无题号单判分处：标题保持（共8分），不合成', () => {
    expect(h3(out)).toContain('七、看图写话：仔细观察图片，写几句话（共8分）');
  });

  it('边界：A 只给类别名时，B 不凭空补作答要求（B 只合成分值）', () => {
    const bare = [
      '<h1>阶段测评</h1>',
      '<h3>四、判断（共10分）</h3>',
      ...Array.from({ length: 5 }, (_, i) => `<p>${i + 1}. 8×3＝24。（2分）</p>`),
    ].join('\n');
    const t = h3(run(bare, 'primary_mid'))[0];
    expect(t, 'B 仍会合成分值').toBe('四、判断（每题2分，共10分）');
    expect(t, 'B 不会凭空补"怎么答"').not.toMatch(/画|√|×/);
  });
});

/** 中学整卷：不设大类层；域型名直接作大题标题（只作范围标识） */
const MIDDLE = [
  '<h1>阶段测评</h1>',
  '<h3>一、数与代数（共30分）</h3>',
  '<p>1. 计算：－3＋5＝____。（10分）</p>',
  '<p>2. 计算：2x－x＝____。（10分）</p>',
  '<p>3. 计算：（－2）×3＝____。（10分）</p>',
  '<h3>二、图形与几何（共20分）</h3>',
  '<p>4. 三角形的内角和是____度。（10分）</p>',
  '<p>5. 正方形有几条对称轴？____条。（10分）</p>',
].join('\n');

describe('整卷端到端 · 中学（无大类层，域型名即大题标题）', () => {
  const out = run(MIDDLE, 'middle');
  console.log('[E2E 中学]', JSON.stringify({ 大类层: h2(out), 大题: h3(out) }));

  it('不设大类层：标题数量＝大题数（无额外 h2 层）', () => {
    expect(h2(out)).toEqual([]);
    expect(h3(out)).toEqual(['一、数与代数（共30分）', '二、图形与几何（共20分）']);
  });

  it('域型名标题只作范围标识：B 不得加单价', () => {
    expect(out).not.toContain('每题10分');
    expect(out).not.toContain('数与代数（每');
    expect(out).not.toContain('图形与几何（每');
  });

  it('题内逐题标注原样保留', () => {
    expect(count(out, /（10分）/g)).toBe(5);
  });
});
