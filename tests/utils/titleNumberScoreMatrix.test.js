// 题号 × 标题 × A × B —— 组合矩阵（2026-10-19 属主："各种可能涉及到的情况全部测试下"）
// ============================================================
// 覆盖维度：
//   D1 题号层：无题号 / 每题带号 / 仅 1 题
//   D2 判分处：每题 1 处 / 多处 / 混合
//   D3 标题初态：共X分 / 裸X分 / 已带单价（每X分，共X分）/ 共1题
//   D4 单价/单位：一致 / 单价不同 / 单位不同 / 缺一条价
//   D5 位置：正文 / 答案区同名
//   D6 学段：小学 / 中学（A 侧条款）
// 判据（现行）：
//   A1 这一组是多件（各自编号）→ 标题（共X分）＋每题后单价；A2 这一组是一件（无题号）→ 单价随标题
//   B  读 A 的逐题标注合成真题标题：同单位同单价→每X分；否则每题总分相同→每题X分；否则按总分分组
// ============================================================
import { describe, it, expect } from 'vitest';
import { auditExamPaper } from '../../src/utils/examValidator.js';
import { getPromptTemplate } from '../../src/config/promptLibrary.js';

const run = (html, stage = 'primary_mid') => auditExamPaper(html, { subject: '数学', stage, genType: 'exam' }).html;
const h3 = (html) => [...html.matchAll(/<h3>([\s\S]*?)<\/h3>/g)].map((m) => m[1]);
const mk = (title, items) => ['<h1>阶段测评</h1>', `<h3>${title}</h3>`, ...items].join('\n');

const NUM5 = Array.from({ length: 5 }, (_, i) => `<p>${i + 1}. 下列正确的是（　）（2分）</p>`);
const BLANK4 = (n) => `<p>${n}. ____ ____ ____ ____（每空1分，共4分）</p>`;

const CASES = [
  { name: '无题号 + 标题已带单价', title: '一、直接写得数（每式1分，共20分）', items: ['<p>4×2＝____　5×3＝____</p>'], expect: '一、直接写得数（每式1分，共20分）' },
  { name: '无题号 + 标题（共15分）', title: '二、看图写话（共15分）', items: ['<p>仔细看图，写几句话。</p>'], expect: '二、看图写话（共15分）' },
  { name: '无题号 + 标题裸（15分）→ 保持（X分）（A 的规定形态）', title: '三、写话（15分）', items: ['<p>写几句话。</p>'], expect: '三、写话（15分）' },
  { name: '有号 + 每题（2分）×5', title: '四、选择（共10分）', items: NUM5, expect: '四、选择（每题2分，共10分）' },
  { name: '有号 + 每题（每空1分，共4分）×2', title: '五、填空（共8分）', items: [BLANK4(1), BLANK4(2)], expect: '五、填空（每题4分，共8分）' },
  {
    name: '有号 + 单位不同、每题总分相同（真机样例）',
    title: '六、填一填（共24分）',
    items: [
      '<p>3. 4个3相加，写成乘法算式是____，读作____。（4分）</p>',
      BLANK4(4), '<p>5. 在○里填上“＞”“＜”或“＝”。（每题1分，共4分）</p>',
      BLANK4(6), BLANK4(7), '<p>8. 得数是12的乘法算式有：____、____。（4分）</p>',
    ],
    expect: '六、填一填（每题4分，共24分）',
  },
  {
    name: '有号 + 每题总分不同 → 按总分分组',
    title: '七、计算（共6分）',
    items: ['<p>1. 3×4＝____（每式1分，共1分）</p>', '<p>2. 12×5＝____（每式2分，共2分）</p>',
      '<p>3. 7×8＝____（每式1分，共1分）</p>', '<p>4. 25×4＝____（每式2分，共2分）</p>'],
    expect: '七、计算（第1、3小题各1分，第2、4小题各2分，共6分）',
  },
  // 🔴 2026-10-20（属主：合成按题的总分）：某题只写（共6分）也有总分 ⇒ 照常合成，不再"不动"。
  { name: '有号 + 某题只写（共6分）→ 仍按题总分合成', title: '八、计算（共12分）',
    items: ['<p>1. 直接写出得数。（每式1分，共6分）</p>', '<p>2. 列竖式计算。（共6分）</p>'], expect: '八、计算（每题6分，共12分）' },
  { name: '有号 + 仅 1 题 → 不合成', title: '九、写话（共15分）', items: ['<p>1. 写几句话。（15分）</p>'], expect: '九、写话（共15分）' },
  { name: '有号 + 标题裸（12分）→ 合成时替换标题分', title: '十、填空（12分）',
    items: ['<p>1. ____ ____ ____ ____ ____ ____（每空1分，共6分）</p>', '<p>2. ____ ____ ____ ____ ____ ____（每空1分，共6分）</p>'],
    expect: '十、填空（每题6分，共12分）' },
  { name: '标题已带单价（幂等）', title: '十一、写话（每篇1分，共8分）', items: ['<p>____</p>'], expect: '十一、写话（每篇1分，共8分）' },
  // 🔴 2026-10-21（属主真机第三次复现后解锁，见 docs/audit/分值与编号-2026-10-21.md）：
  //   原期望"标题已带单价（幂等）⇒ 不动"＝B 不管这个形态。但 A 侧反复没落地"标题写单价 ⇔ 其下无题号"，
  //   B 又跳过 ⇒ 缺陷永久留在产物里。现口径：**有带号子题时标题只能是（共X分）/合成式**，
  //   标题写单价即属错位，B 按逐题总分照常合成（不改数、不删正文）。
  { name: '有号 + 标题写了单价（错位）→ 按逐题总分合成', title: '十一B、填空（每空1分，共8分）', items: [BLANK4(1), BLANK4(2)], expect: '十一B、填空（每题4分，共8分）' },
  { name: '有号 + 半角括号标题（共10分）', title: '十一C、选择(共10分)', items: NUM5, expect: '十一C、选择（每题2分，共10分）' },
  { name: '标题“共1题，共15分” + 1 题 → 不动', title: '十二、写话（共1题，共15分）', items: ['<p>1. 写几句话。（15分）</p>'], expect: '十二、写话（共1题，共15分）' },
  {
    name: '多档 + 单位不同 + 总分不同 → 按总分分组',
    title: '十三、计算（共8分）',
    items: ['<p>1. ____ ____（每空1分，共2分）</p>', '<p>2. 列式计算。（每处2分，共6分）</p>'],
    expect: '十三、计算（第1小题2分，第2小题6分，共8分）',
  },
  {
    name: '病态：标题总数不符 → B 按题内之和合成（不改数）',
    title: '十四、判断（共10分）',
    items: [
      '<p>9. 判断下面各题，对的在括号里画“√”，错的画“×”。（每题2分，共10分）</p>',
      ...Array.from({ length: 9 }, (_, i) => `<p>${10 + i}. 8×3＝24（　）（2分）</p>`),
    ],
    expect: '十四、判断（第9小题10分，第10、11、12、13、14、15、16、17、18小题各2分，共28分）',
  },
];

describe('题号×标题×A×B 组合矩阵', () => {
  for (const c of CASES) {
    it(c.name, () => {
      const out = run(mk(c.title, c.items));
      const got = h3(out)[0];
      console.log(`[矩阵] ${c.name} ⇒ ${got}`);
      expect(got).toBe(c.expect);
    });
  }

  it('答案区同名大题标题同步合成（正文＋答案区各一处）', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>十四、填空（共4分）</h3>', '<p>1. ____ ____（每空1分，共2分）</p>', '<p>2. ____ ____（每空1分，共2分）</p>',
      '<h2>参考答案与评分标准</h2>',
      '<h3>十四、填空（共4分）</h3>', '<p>1. 答案（每空1分，共2分）</p>', '<p>2. 答案（每空1分，共2分）</p>',
    ].join('\n');
    const out = run(html);
    expect((out.match(/十四、填空（每题2分，共4分）/g) || []).length).toBe(2);
  });

  // 🔴 2026-10-24（属主定基准·单一开关）：编号是总开关、标分跟着编号走。
  //   第①步只判"这一组各项有没有只属于它自己的题干话"；带号 ⇒ 逐题标分、标题分由程序合成；
  //   不带号 ⇒ 不写号、单价只在大标题、题内不标分。旧"成题区/直答区"两把尺与"一题一标（成题区）"全部清除。
  it('A 侧：编号一个开关、标分跟着编号走（两学段）', () => {
    for (const stage of ['primary_low', 'middle']) {
      const t = getPromptTemplate({ grade: stage, subject: '数学', genType: 'exam' }).template;
      expect(t, '第一步：先看整组、再定编号').toContain('号是点名用的');
      expect(t, '唯一判据＝有没有只属于它自己的题干话').toContain('各项有只属于它自己的题干话');
      expect(t, '一组只做一个动作（不得一半一半）').toContain('一组只做一个动作');
      expect(t, '不编号 ⇒ 不写小题号').toContain('只有作答内容本身、没有只属于它的话');
      expect(t, '不编号 ⇒ 分值只写在大标题').toContain('分值只写在大标题');
      expect(t, '不编号 ⇒ 题内不标分').toContain('题内不标分');
      expect(t, '编号 ⇒ 逐题标分（位置按真题习惯）').toContain('该题最后一行末尾');
      expect(t, '编号 ⇒ 标题不重复小题分值').toContain('标题里不再重复小题分值');
      // 🔴 2026-10-24（属主真卷：大标题无分、全卷差 26 分）：无论带不带号，大标题括注都要给该大题总分——
      //   否则编号一判错、逐题分又没写，这一大题的分数就凭空消失。
      expect(t, '大标题必带该大题总分').toContain('标题括注始终写该大题总分');
      // 🔴 2026-10-24（真机"带号题全没标分"）：A 侧不得提"标题分由程序合成"——
      //   模型会把它当成"省掉逐题标分"的理由（程序合成属 B 侧实现，不进模型判据）。
      expect(t, 'A 侧不得提"程序合成标题分"').not.toContain('标题分由程序按各题分合成');
      expect(t, '带号 ⇒ 每道带号小题都要有自己的分值').toContain('每道带号小题都要有自己的分值');
      expect(t, '带号支：一处裸分／多处全式').toContain('一题一处判分写');
      expect(t, 'Y 与该题实际判分处数相符').toContain('Y 与该题实际判分处数相符');
      expect(t, '一处 ⇒ 裸分').toContain('一题一处判分写');
      expect(t, '多处 ⇒ 全式带单位').toContain('多处判分写');
      expect(t, '合计自洽（不写进标题）').toContain('合计自洽');
      // 🔴 2026-10-24（属主："不要人为干预模型的能力"）：两句禁令已删——"不得整组一律"把
      //   "每空1分"这种组内统一也一并否掉，"不得为凑总分编题"又把"增减一处补平差额"堵住，
      //   模型只剩"承认差额"（24 vs 23）。改为反向锁，防这两句回潮。
      expect(t, '"不得整组一律"不得回潮').not.toContain('不得整组一律');
      expect(t, '"不得为凑总分编题"不得回潮').not.toContain('不得为凑总分编题');
      expect(t, '② 完整性判据（每道小题都要标）').toContain('漏标一题即不合规');
      expect(t, '号与分互锁').toContain('不许只有号没有分，也不许没有号却在题内标分');
      // 🔴 2026-10-24 真机（"一、直接写出得数""二、列竖式计算"整栏题不编号了，但标题无分、全卷差 26）：
      //   两处标题样例原写成不带分的形状，与"不带号：分值只写在大题标题括注里"互相矛盾，模型照样例走。
      //   ⇒ 样例一律带**大题总分**（仍不带单价/小题分）。
      expect(t, '分值标注里的标题样例带该大题总分').toContain('形如"一、〈名称〉（共X分）"');
      expect(t, '输出格式的 h2 样例带该大题总分').toContain('如 <h2>一、〈大题名〉（共X分）</h2>');
      expect(t, '标题样例仍不带单价/小题分').not.toMatch(/形如"一、〈名称〉（每题/);
      // 🔴 2026-10-24（属主："没有小题号的大标题要标单价"）：不带号支原为"（共X分）或（每…）"的许可式，
      //   等于允许只写总分、丢掉单价。改为唯一形态，单价不可省。
      expect(t, '不带号支：唯一形态且单价不可省').toContain('写"（每〈单位〉X分，共Y分）"、**单价不可省**');
      expect(t, '不带号支不得留"或"的许可式').not.toContain('"（共X分）"或"（每〈单位〉X分，共Y分）"');
      expect(t, '旧"（分值说明）"不得回潮').not.toContain('（分值说明）');
      expect(t, '要求不得写成带号题干').toContain('不得把这条要求写成带题号的题干');
      // 反向锁：旧两区名／旧补救句／旧第二把尺／旧"先写题后标分"机制句，都不得回潮。
      expect(t, '旧两区名不得回潮').not.toMatch(/成题区|直答区/);
      expect(t, '旧"多件/一件"两支不得回潮').not.toContain('这一组是多件');
      expect(t, '旧"补救句"不得回潮').not.toContain('标题若已写成单价');
      expect(t, '第二把尺（独立作答要求）不得回潮').not.toContain('各自是一道要作答的题');
      expect(t, '编号判据不得在标题块再写一份').not.toContain('题号只给要单独点名的题');
      expect(t, '旧"先写题、再标分、后核分"不得回潮').not.toContain('先写题、再标分、后核分');
    }
  });

  it('A 侧：大题序号只关汉字号（不推到题号）', () => {
    const t = getPromptTemplate({ grade: 'primary_low', subject: '数学', genType: 'exam' }).template;
    expect(t).toContain('只关汉字大题号，不推到题号');
  });

  // 🔴 2026-10-19（属主：大类名分小学/中学、位置不一样）：例外不能写成"全局可只作范围标识"。
  //   小学：大类（部分）层在大题之上，大类名**不得充当大题标题**；大题标题一律完整（无例外）。
  //   中学：不设大类层，域型名**直接作大题标题**、可只作范围标识；作答形式名两学段都要就地补齐。
  it('A 侧：大类名的位置按学段分（小学不得作标题；中学域型名直接作标题）', () => {
    const pri = getPromptTemplate({ grade: 'primary_low', subject: '数学', genType: 'exam' }).template;
    const mid = getPromptTemplate({ grade: 'middle', subject: '数学', genType: 'exam' }).template;
    // 小学
    expect(pri, '小学：大类名不得充当大题标题').toContain('不得充当大题标题');
    expect(pri, '小学：大题标题本身须是完整作答要求').toContain('大题标题本身须是完整的作答要求');
    expect(pri, '小学：不得出现"只作范围标识、不加作答要求"的例外').not.toContain('只作范围标识、不加作答要求');
    // 中学
    expect(mid, '中学：不设大类层').toContain('不设大类层');
    expect(mid, '中学：域型名只作范围标识').toContain('域型名');
    expect(mid, '中学：域型名不加作答要求').toContain('只作范围标识、不加作答要求');
    // 两学段共有：作答形式名就地补齐
    for (const [name, t] of [['小学', pri], ['中学', mid]]) {
      expect(t, `${name}：作答形式名须在原标题行内补齐`).toContain('作答形式名须在');
      expect(t, `${name}：不另起一行`).toContain('原标题行内');
    }
  });
});
