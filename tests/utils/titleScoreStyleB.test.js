// B·真题标分样式（渲染期）——A+B 的 B 侧
// ============================================================
// 分工（属主 2026-10-19 澄清）：A 不能直接产出真题样式且保证分值/内容自洽，
//   故 A 只逐题标「每〈单位〉X分，共Y分」（单判分处只写「X分」），
//   B 读这些标注，把**大题标题**合成为真题写法：
//     ① 单价唯一 → 「（每〈单位〉X分，共Y分）」；
//     ② 多档 → 分组式「（第1、3小题各1分，第2、4小题各2分，共6分）」。
//   不改数、不做除法、不删正文；题内标注保留（逐题对账的落点）。
// ============================================================
import { describe, it, expect } from 'vitest';
import { auditExamPaper } from '../../src/utils/examValidator.js';

const OPTS = { subject: '数学', stage: 'primary_mid', genType: 'exam' };
const run = (html) => auditExamPaper(html, OPTS);
const titles = (html) => [...html.matchAll(/<h[2-4]>([\s\S]*?)<\/h[2-4]>/g)].map((m) => m[1]);

describe('B：把 A 的逐题标注合成为真题标题', () => {
  it('单价唯一（每空1分）→ 标题「（每空1分，共24分）」，题内 6 条标注保留', () => {
    const items = Array.from({ length: 6 }, (_, i) => `<p>${i + 1}. ____ ____ ____ ____（每空1分，共4分）</p>`);
    const html = ['<h1>阶段测评</h1>', '<h3>一、填空（共24分）</h3>', ...items].join('\n');
    const r = run(html);
    expect(titles(r.html)).toContain('一、填空（每空1分，共24分）');
    expect((r.html.match(/每空1分，共4分/g) || []).length, '题内标注不得被删').toBe(6);
    expect(r.issues.some((x) => x.type === 'title-detail' && x.message.includes('真题标分样式'))).toBe(true);
  });

  it('单判分处只写（2分）→ 标题「（每题2分，共10分）」，题内（2分）保留', () => {
    const items = Array.from({ length: 5 }, (_, i) => `<p>${i + 1}. 下列正确的是（　）（2分）</p>`);
    const html = ['<h1>阶段测评</h1>', '<h3>二、选择（共10分）</h3>', ...items].join('\n');
    const r = run(html);
    expect(titles(r.html)).toContain('二、选择（每题2分，共10分）');
    expect((r.html.match(/（2分）/g) || []).length, '题内（2分）全保留').toBe(5);
  });

  it('多档（每式1分/2分）→ 分组式', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>三、计算（共6分）</h3>',
      '<p>1. 3×4＝____（每式1分，共1分）</p>',
      '<p>2. 12×5＝____（每式2分，共2分）</p>',
      '<p>3. 7×8＝____（每式1分，共1分）</p>',
      '<p>4. 25×4＝____（每式2分，共2分）</p>',
    ].join('\n');
    expect(titles(run(html).html)).toContain('三、计算（第1、3小题各1分，第2、4小题各2分，共6分）');
  });

  it('多档但每题总分相同 → 按"每小题X分"（单价差异留在题内标注）', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>四、计算（共12分）</h3>',
      '<p>1. 直接写出得数。（每式1分，共6分）</p>',
      '<p>2. 列竖式计算。（每式2分，共6分）</p>',
    ].join('\n');
    const out = titles(run(html).html);
    expect(out).toContain('四、计算（每小题6分，共12分）');
    expect(out.join('|'), '不得拿单价冒充题分').not.toContain('第1小题1分');
  });

  it('有题没标价（归不了类）→ 不动，标题保持「（共12分）」', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>五、计算（共12分）</h3>',
      '<p>1. 直接写出得数。（每式1分，共6分）</p>',
      '<p>2. 列竖式计算。（共6分）</p>',
    ].join('\n');
    expect(titles(run(html).html)).toContain('五、计算（共12分）');
  });

  it('无编号（整栏并列）→ 不动（A 已把单价写在标题）', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>六、直接写得数（每式1分，共20分）</h3>',
      '<p>4×2＝____　5×3＝____</p>',
    ].join('\n');
    expect(titles(run(html).html)).toContain('六、直接写得数（每式1分，共20分）');
  });

  it('单位/单价不一但每题总分相同 → 按"每小题X分"（不得拿单价冒充题分）', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>三、填一填（共24分）</h3>',
      '<p>3. 4个3相加，写成乘法算式是____，读作____。（4分）</p>',
      '<p>4. 把口诀补充完整。（每空1分，共4分）</p>',
      '<p>5. 在○里填上"＞""＜"或"＝"。（每题1分，共4分）</p>',
      '<p>6. 文具店里一盒橡皮有6块。（每空1分，共4分）</p>',
      '<p>7. 在括号里填上合适的数。（每空1分，共4分）</p>',
      '<p>8. 得数是12的乘法算式有：____、____。（4分）</p>',
    ].join('\n');
    const out = titles(run(html).html);
    expect(out).toContain('三、填一填（每小题4分，共24分）');
    expect(out.join('|'), '不得出现"第4、5、6、7小题各1分"（单价冒充题分）').not.toContain('各1分');
  });

  it('答案区同名大题标题同样合成（同一规则跑整份）', () => {
    const html = [
      '<h1>阶段测评</h1>',
      '<h3>一、填空（共8分）</h3>',
      '<p>1. ____ ____（每空1分，共2分）</p>',
      '<p>2. ____ ____（每空1分，共2分）</p>',
      '<h2>参考答案与评分标准</h2>',
      '<h3>一、填空（共8分）</h3>',
      '<p>1. 答案（每空1分，共2分）</p>',
      '<p>2. 答案（每空1分，共2分）</p>',
    ].join('\n');
    const out = run(html).html;
    expect((out.match(/一、填空（每空1分，共8分）/g) || []).length, '正文与答案区都合成').toBe(2);
  });
});
