// 🔢 题号"编号对象"口径守卫（2026-09-30 用户裁定·调研后落）
// 调研结论（19 条实样来源，见 docs/design/标题层级与编号规范.md §五）：编号单位 = 一个独立作答/可判分的小题；
//   同型并列栏目整栏不逐项编号；一段材料作为一个题时只给一个题号，段内多空不编号。
// 本条只管**小题号的编号对象**；大题序号（全卷连续）与分值标注照既有条款不变；符号不指定（防定形诱导）。
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { getPromptTemplate, QUESTION_OBJECT_CALIBER, QUESTION_NUMBERING_CALIBER, SCORING_OBJECT_CALIBER } from '../../src/config/promptLibrary.js';

const ROOT = path.resolve(__dirname, '../..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const tpl = (g, s = '语文', st = 'primary_low') => getPromptTemplate({ grade: st, subject: s, genType: g }).template;

describe('题号"编号对象"口径', () => {
  it('考卷与教辅两条通道都携带该条（单源一次定义、两处引用）', () => {
    const lib = read('src/config/promptLibrary.js');
    expect((lib.match(/export const QUESTION_OBJECT_CALIBER/g) || []).length, '只允许一处定义').toBe(1);
    expect((lib.match(/QUESTION_OBJECT_CALIBER/g) || []).length, '定义 1 + 消费 2').toBe(3);
    for (const g of ['exam', 'practice', 'special', 'reading', 'review']) {
      expect(tpl(g), `${g} 应携带编号对象口径`).toContain(QUESTION_OBJECT_CALIBER);
    }
  });

  it('只管编号对象：大题序号顺序编（不重新起头）与分值标注不得被削弱', () => {
    const ex = tpl('exam');
    expect(ex, '大题序号：一、二、三…（跨大类/部分接着编）仍在').toContain('跨大类/部分接着编');
    expect(ex, '⚠️「全卷连续」四字不得回潮（会被读成题号层也连续 ⇒ 每个题干都要给号）').not.toContain('全卷连续');
    expect(ex, '账目逐层判词仍在（独立题干→大题→大类→满分）').toContain('大题总分＝其下各独立题干分之和');
    expect(QUESTION_OBJECT_CALIBER, '按 id 锚定：条目存在且声明只管编号层（语义族断言，不锁字面）').toMatch(/题号只标|编号的?\*\*层级/);
    // 🔴 2026-10-10（属主裁定·删编法规定）：`QUESTION_NUMBERING_CALIBER.teaching` 已整块删除，该断言随之撤除。
  });

  it('零诱导：不点题型名、不指定分问符号', () => {
    // 🔴 2026-10-10（〔332〕单位取"作答什么"的通称，不写载体形态名）：原"单位即该载体"字面会产出"每横线1分／每括号1分" ⇒ 改判据＋锁。
    // 🔴 2026-10-11（T03·G61）：「通称」无锚（不可自判）⇒ 改**可判法**——单位＝该处让学生作答**什么**的**名称**，
    //    并点明**不得写空位形态名**（横线／括号／书写格）。
    // 🔴 2026-10-17（属主裁定·"这个枚举不可以，定死了…要考虑全，不要仅为了好数而失真"）：G61 当时补的
    //    "汉字／词语／数字／字母／选项"枚举**已删**——枚举把注意力钉在那几个词上、诱导内容往枚举上凑，
    //    反而漏掉该学段通行的其它作答对象。判据（名称＋不写载体形态名）两半已可自判 ⇒ 断言随之改准：
    //    锁"判据仍在"，并加**反向锁**防枚举回潮。
    expect(SCORING_OBJECT_CALIBER, '单位＝作答对象的名称（可判法）').toContain('单位取"该处让学生作答什么"的名称');
    expect(SCORING_OBJECT_CALIBER, '枚举不得回潮（会诱导往枚举上凑、并漏掉其它作答对象）').not.toMatch(/汉字／词语|词语／数字|数字／字母|字母／选项/);
    expect(SCORING_OBJECT_CALIBER, '不得写载体形态名').toContain('不得写承载它的空位形态名');
    expect(QUESTION_OBJECT_CALIBER).not.toMatch(/看拼音|组词|连一连|口算|竖式|选择|判断|填空|选字|选词/);
    expect(QUESTION_OBJECT_CALIBER).not.toMatch(/①|②|（1）|\(1\)/);
    expect(QUESTION_OBJECT_CALIBER, '编号对象＝独立作答单位（语义族）').toMatch(/独立作答单位|编号的?\*\*层级/);
  });

  // ⛔ 2026-10-10（属主裁定·**删编法规定·去约束**）：原"旧口径不得被覆盖：全卷连续/逐栏目起编两套仍在
  //   （不得互相否定）"**整档撤除**——小题号**编法**（含"不得互相否定"分型尾句）已按同一裁定**整体删除**；
  //   "哪些题该编号"由【编号对象口径】单源承载，"号怎么排"不作规定即最正规。（原断言见 git 历史。）

  // 🔴 2026-10-03（用户报障根治·问题5）：「共N题」题量原写"只数**实际给号的小题**"——与账目绝对等式
  //    （小题数×每题分=大题分）耦合，模型为凑等式把同型并列小项**逐项编号**（生编硬凑题号）。
  //    已把"共N题/小题数"口径显式指向本题号对象条。本用例为**锁**：该耦合口径不得回潮。
  it('题量口径：不再有"题量"预载（计数统一按计分对象），且禁止为凑数逐项编号', () => {
    const ex = tpl('exam');
    // 🔴 2026-10-10（〔328〕三口径闭环）：原"账目里的**题量**按上条口径计"是**题数时代**的残留——
    //    题数已废、账目改以**计分对象**计数 ⇒ 该预载删；防凑编号的禁句保留（改中性词"凑数"）。
    expect(ex, '"题量"预载已废（计数统一按计分对象）').not.toContain('题量');
    // 🔴 2026-10-12（S4 差集·属主方向「否定表达不好」）：原禁句"不得为凑数逐项编号"**改正向**——
    //    判据改述为"条数由实际内容决定"（语义同、不再用否定式）。
    // 🔴 2026-10-16（相抵根治·N1）：原句"**编号与**计分按实际计分对象给出"与同块【计分对象】口径
    //    "与编号对象不是同一把尺——题号给'独立作答单位'、分数给'判分处'；一个编号对象下可有多个计分对象"
    //    **同块相抵**：填空（1 编号对象／24 计分对象）按前者编 24 个号、按后者只编 1 个 ⇒ 实测"不该编号的题被编号"。
    //    处置＝删"编号与"三字；编号对象**单源＝QOC**，本条只讲计分条数。本锁：旧句不得回潮。
    expect(ex, '计分条数由实际内容决定的判据须在位').toContain('条数由实际内容决定');
    expect(ex, '旧"编号与计分按实际计分对象给出"不得回潮（与计分对象口径相抵）').not.toContain('编号与计分按实际计分对象给出');
    expect(ex, '否定式旧句不得回潮').not.toContain('不得为凑数逐项编号');
    expect(QUESTION_OBJECT_CALIBER, '编号对象条须含"共用要求的一批同类项整栏不逐项编号"').toMatch(/共用同一条作答要求|同层同构/);
    // 🔴 2026-10-10（面5·四问②对象锚不适配）：原"整栏"是**教辅容器术语**（术语映射仅对题类教辅生效），
    //   而 **exam 只有大类/大题、并无"栏"** ⇒ 该"不编号"支在 exam 侧无对应物、不可自判（产物实证：大题下同型并列仍硬编小题号）。
    //   已去"整栏"改层级无关（"…一批同类项不逐项编号"）。本条为锁：**"整栏"不得回潮**。
    expect(QUESTION_OBJECT_CALIBER, '去"整栏"（层级无关·exam 无"栏"）').not.toContain('整栏');
    // 🔴 2026-10-04（四问复核·①可自判）：原"同型并列小项"与"互不相同独立任务"对同一对象可同时成立
    //   （6 道同型选择题：既"同型"又"独立"）→ 边界不可自判。改为**可自判判据**："各自给出独立设问的"才各自编号
    //   （选择题各带独立问题与作答对象 → 各自编号；看拼音写词语/口算＝共用一条要求的待填同类项 → 不编号）。
    // 🔴 2026-10-16（相抵根治·N2）：原判词"独立设问的（**逐项设问不同**）"与同条前半"共用同一条作答要求…
    //    把包装那半句删去，作答动作不变 ⇒ 不得另起题号"**对同一对象给相反答案**（口算"3+5=／7-2="逐项
    //    "设问不同"却"作答动作相同"）⇒ 模型时编时不编。处置＝判词统一为"作答要求"一把尺。
    expect(QUESTION_OBJECT_CALIBER, '判据须点明"各自给出独立作答要求的才各自编号"').toMatch(/独立作答要求|异层异构/);
    expect(QUESTION_OBJECT_CALIBER, '旧"逐项设问不同"不得回潮（与"作答要求不变"相抵）').not.toContain('逐项设问不同');
  });

  // 🔴 2026-10-10（〔335〕属主令"挂着的就自己测掉"）：〔333〕H2／H3 两项**观察项转锁**——自测通过即销案、不再挂观察。
  it('H2 反锁：否定式点名句不得回潮（防"点名即强调"的反诱导）', () => {
    expect(QUESTION_OBJECT_CALIBER, '"同一次作答动作内的多个待填位置…"式否定点名已删').not.toContain('同一次作答动作');
    expect(QUESTION_OBJECT_CALIBER, '同类项条须为正面表述（整批只给一个题号）').toMatch(/整批|同层同构/);
  });
  it('H3 自测：卷面层级给"正面出口"（可不设题号层）——不再靠跨块指向；题号条只给对象词、不得复述指针', () => {
    const ex = tpl('exam');
    // 🔴 2026-10-16（连通组·编号组·就地展开）：原锚"编号对象指针**唯一**——卷面层级持有"（指针字面
    //    '哪些题该编号，见【题号与分值】的编号对象口径'）——该指针是 2026-10-09 为消"双源相抵"而设的处置，
    //    但**跨块指向**恰是模型"自己拼装"的根（属主裁定：通起来、**就地展开优先**）。现改为
    //    **就地给正面出口**（"可以只有大题标题一层"），指针与元话语一并删除。
    expect(ex, '正面出口：可只有大题标题一层（不为连续性补号）').toContain('可以只有大题标题一层');
    expect(ex, '旧跨块指向不得回潮（模型不再需要跨块拼装）').not.toContain('哪些题该编号，见【题号与分值】');
    expect(ex, '题号条改为结构式：每个独立题干都用 question 包裹（给不给号都包裹）').toContain('每个独立题干用 <p class="question"> 包裹');
    expect(ex, '⚠️「应编号的题」定名不得回潮（预设有一批应给号的题）').not.toContain('**应编号的题**');
  });

  // 🔴 2026-10-10（〔346〕产物实证·编号冲动根因·解锁后销案）：原"全大题仅一个小题时"**不可自判**——
  //    模型把整大题下并列的算式/项当成"多个小题"⇒ 判据不触发 ⇒ 仍长"1. 直接写出下面各题的得数。"、
  //    游园会读音项被编成 2./3./4./5.。改成**可自判锚**："整大题只含一个编号对象时（＝共用一条作答要求，
  //    哪怕其下并列多少项）"。本条为锁：不可自判的旧锚不得回潮、"不再另起小题号与题干行"判词保留。
  it('〔346〕编号冲动根因：可自判锚"整大题只含一个编号对象时"在位；不可自判的旧锚不得回潮', () => {
    expect(QUESTION_OBJECT_CALIBER, '可自判锚在位').toMatch(/整大题只含一个编号对象|一个编号对象时/);
    expect(QUESTION_OBJECT_CALIBER, '共用一条要求＝一个编号对象（哪怕并列多少项，防"并列即多小题"）').toMatch(/并列多少项|共用一条作答要求/);
    expect(QUESTION_OBJECT_CALIBER, '不可自判的旧锚不得回潮').not.toContain('全大题仅一个小题时');
    // 🔴 2026-10-11（属主·自洽体检）：判词改中性（去"小题"预设）——"其下不再另起**题号**与题干行"。
    expect(QUESTION_OBJECT_CALIBER, '治「1. 直接写出得数。」的判词保留').toMatch(/不再另起题号/);
    // 【卷面自洽】"不另起同文题干"同用该旧锚 ⇒ 一并改准（同锚不同事）；全卷不得残留旧锚。
    expect(tpl('exam'), '卷面自洽条旧锚须一并改准').not.toContain('全大题仅一个小题时');
  });

  // 🔴 2026-10-10（〔340〕多源取证·两处"疑似"当场转锁）：M5／③ 经取证**均非拉扯** ⇒ 写成锁，挂账清零。
  it('M5 自测：教辅"组标题自拟"与"只写作答方式"**同份在场**——来源 vs 写法两维，非同源冲突', () => {
    const t = tpl('practice');
    expect(t, '组标题来源句在场（自拟）').toContain('标题自拟');
    expect(t, '组标题写法句在场（只说明本组实际的作答方式）').toContain('组标题只说明本组');
  });
  it('③ 自测：内容型栏目标题样例取自**名称池**（轮换多套 ⇒ 非硬编样例、不触趋同）', () => {
    const lib = read('src/composables/useAiGenerator.js');
    const m = /summary:\s*\[([^\]]+)\]/.exec(lib);
    expect(m, '内容型名称池须存在').toBeTruthy();
    expect((m[1].match(/'/g) || []).length, '池内 ≥2 套（轮换）').toBeGreaterThanOrEqual(4);
    expect(m[1], '样例名取自池').toContain('知识梳理');
  });
});
