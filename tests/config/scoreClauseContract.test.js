// ============================================================
// 分值标注 · 骨架契约（2026-10-28 属主 A/B 澄清版）
// ------------------------------------------------------------
// 覆盖面：**全部 54 个 学科×学段 组合**（STAGE_SUBJECTS 实际开设矩阵）× exam，不抽样。
// 只锁**判据骨架**（每条判据各管一件事、各写一处）与**回潮**，不锁整句措辞。
// 来历（提交史）：b840e7a 成功版 → 200377e 完美版（标题 Σ ＋ 题内）
//   → 2026-10-28 属主两轮澄清：
//     ① "小题标分是独立判据吗？没有与大题标题混用吧？" ⇒ 判据各自成条、各写一处；
//     ② "标题要写，模型侧写，但不是逆写作顺序——模型写卷先定大框架（大题），一开始就分配好了"
//        ⇒ 标题上的数是**分配值**，写在最前是对的；核对是"各题之和＝标题所写"。
//   故本契约锁两件事：标题条与题内条各自独立（不得并成一条）、"先分配、后落实"在位
//   （缺它，标题的合计就只能读成"事后求和"，才会一改就崩）。
// 附带守卫：实发正文不得混入源码注释标记（🔴/属主/病根/真题实证/TODO）。
import { describe, it, expect } from 'vitest';
import { getPromptTemplate, STAGE_SUBJECTS } from '../../src/config/promptLibrary.js';

const PAIRS = Object.entries(STAGE_SUBJECTS)
  .flatMap(([stage, subjects]) => subjects.map((subject) => ({ stage, subject })));

/** 判据骨架：每条判据各自成条、各管一件事；缺一即红 */
const REQUIRED = [
  ['结构判定（遮住标题、只看一项）', /遮住大题标题[、，]?只看其中一项/],
  ['写作顺序：先分配、后落实', /先分配、后落实/],
  ['单题干：分写在标题后（一处）', /单题干（整栏合一）\*\*：\*\*分写在标题后\*\*/],
  ['多题干：分写在每题题干后（一处）', /多题干（逐题独立）\*\*：\*\*分写在每题题干后\*\*/],
  ['多题干：Y 只算这一题', /Y 只算这一题/],
  ['大题标题同样写它分到的那一份', /大题标题同样写它分到的那一份/],
  ['标题的单价不代替题内（共Y＝各题之和）', /标题里的共Y要和这些分之和相等/],
  ['位置：写在全部材料与作答载体之后', /全部材料与作答载体之后/],
  ['位置：选项题写在选项列表之后', /选项列表之后/],
  ['单价：先定单价、后乘个数', /Y＝X×N/],
  ['单价：取该学段通行的分值档（不枚举档值）', /该学段通行的分值档/],
  ['单价：不得倒推', /不得先定总分再倒推单价/],
  ['验算：大题总分＝其下各题 Y 之和', /该大题总分＝其下各题 Y 之和/],
  ['验算：各大题分之和＝给定满分', /各大题分之和＝给定满分/],
  ['验算：满分不可改', /不得改动满分/],
  ['答案区镜像判据（不自行拟分）', /答案区不自行拟分\*\*：分值镜像正文/],
  ['答案区小题分来源（同题号、整串照抄）', /分写在序号之后[^。]{0,40}整串照抄/],
  ['答案区小题不重算（照抄而非换算）', /不改写、不换算/],
];

/** 回潮：出现即红（这些是已废除的第二套判据，不是"曾经好用的句子"） */
const FORBIDDEN = [
  ['旧：大题标题只写标题名（标题不写分）', /大题标题只写标题名/],
  ['旧：标题一律写（每〈单位〉X分，共ΣY分）', /共ΣY分/],
  ['旧：（共Y分）中间态', /大题标题写"（共Y分）"/],
  ['旧：题内标分只看有没有号', /有号的题：每题题干后必须标/],
  ['旧：指定具体单位词', /〈单位〉写"题"/],
  ['旧：分写在**大题标题后**（单支规定）', /分写在\*\*大题标题后\*\*/],
  ['旧：输出格式复述两支', /逐题独立时标题写|整栏合一时标题写/],
  ['旧：题目自洽②复述位置子规则', /不得脱离题干另起一行/],
];

/** 源码注释标记：不得进实发 */
const COMMENT_MARKS = ['🔴', '属主', '病根', '真题实证', 'TODO'];

const tplOf = (subject, stage) => getPromptTemplate({ grade: stage, subject, genType: 'exam' }).template;

describe('分值标注骨架契约（全部 54 个 学科×学段）', () => {
  it(`覆盖面：${PAIRS.length} 个组合全部在册（不抽样）`, () => {
    expect(PAIRS.length, '学科×学段 实际开设组合数').toBe(54);
  });

  for (const { stage, subject } of PAIRS) {
    it(`${subject}/${stage}：判据骨架都在、回潮都无、块数=1`, () => {
      const t = tplOf(subject, stage);
      for (const [name, re] of REQUIRED) expect(re.test(t), `缺：${name}`).toBe(true);
      for (const [name, re] of FORBIDDEN) expect(re.test(t), `回潮：${name}`).toBe(false);
      expect((t.match(/(?:^|\n)【分值标注/g) || []).length, '【分值标注】块数须为 1（新旧并存即红）').toBe(1);
    });
  }

  it('实发正文不混入源码注释标记（54 组合逐个查）', () => {
    const bad = [];
    for (const { stage, subject } of PAIRS) {
      const t = tplOf(subject, stage);
      for (const m of COMMENT_MARKS) if (t.includes(m)) bad.push(`${subject}/${stage}：出现「${m}」`);
      const block = (t.match(/(?:^|\n)【分值标注[^】]*】([\s\S]*?)(?=\n【|$)/) || [, ''])[1];
      if (block.includes('//')) bad.push(`${subject}/${stage}：分值标注块内出现 //`);
    }
    expect(bad.slice(0, 8), '注释标记不得进实发').toEqual([]);
  });

  it('守卫有牙：把"多题干落在题干后"并回标题即判红（题内那处被吞掉）', () => {
    const t = tplOf('数学', 'primary_low');
    const merged = t.replace(/\*\*多题干（逐题独立）\*\*：\*\*分写在每题题干后\*\*/, '**大题标题写法**：**一律写在标题后**');
    expect(/多题干（逐题独立）\*\*：\*\*分写在每题题干后\*\*/.test(t)).toBe(true);
    expect(/多题干（逐题独立）\*\*：\*\*分写在每题题干后\*\*/.test(merged)).toBe(false);
  });

  it('守卫有牙：删掉"先分配、后落实"即判红（复现"标题数只能事后求和"的读法）', () => {
    const t = tplOf('数学', 'primary_low');
    const broken = t.replace(/先分配、后落实/g, '先写题、后加总');
    expect(/先分配、后落实/.test(t)).toBe(true);
    expect(/先分配、后落实/.test(broken)).toBe(false);
  });
});
