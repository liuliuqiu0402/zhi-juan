// 🔒 判据级"唯一出现"守卫（2026-09-30 用户裁定：判据是公共的；进发模型的每个判据只能出现一次）
// ============================================================
// 与 promptGrowthGuard（关键词条数上限）的区别：本守卫按**判据**（一条正则＝一个判据）断言**恰好出现一次**——
// 判据级而非关键词级，避免"同性质"这种跨管域的词被误当同义（实测该词横跨三个不同判据：同题内一致／同卷统一／不得另起载体）。
// 纪律：收紧一个锁一个（先把已核实冗余的判据收到 1，其余分批推进），避免一次性大改。
import { describe, it, expect } from 'vitest';
import { getPromptTemplate } from '../../src/config/promptLibrary.js';

const tpl = (g = 'exam', s = '语文', st = 'primary_low') => getPromptTemplate({ grade: st, subject: s, genType: g }).template;
const count = (t, re) => (t.match(re) || []).length;

/** 判据 → 唯一性要求（每项：说明 + 正则 + 期望次数） */
const CALIBERS = [
  {
    name: '同题内同性质载体形态一致',
    re: /同一题内同性质作答载体|同一题（含并列各项）同性质空位的形态一致/g,
    // 🔴 2026-10-11（T13·G101）：题类自洽**⑥**（"同一题内同性质作答载体形态一致（判据见作答位条款，此处不另立）"）
    //   属**纯引用＋元话语自指** ⇒ **整条删除**（其判据单源在作答位条款）⇒ 正句由 2 处回到 1 处。
    want: 1,
  },
  {
    name: '同卷空位形态统一',
    re: /同卷空位形态统一/g,
    want: 1,
  },
  {
    // 🔴 2026-10-01（用户裁定"一份实发内不得多块同义"）：自洽⑤ 已改为**引用式**
    //    （"同性质作答空位的去重、长答例外与并存情形，判据见作答位条款，此处不另立"），
    //    本判据的唯一正句落在**作答位条款**（layoutSpec，写作"不得再**在题后**另起…"）。
    //    正则随之**收紧**为 /不得再[^，。；\n]{0,10}另起/——旧 /不得再另起/ 会被"在题后另起"绕过（守卫漏网，本轮已补）。
    name: '不得另起同性质整行短答载体',
    re: /不得再[^，。；\n]{0,10}另起/g,
    want: 1,
  },
];

describe('判据级"唯一出现"守卫（每判据只准一处正句，其余只能引用）', () => {
  it('已收口判据在试卷模板中各只出现规定次数', () => {
    const bad = [];
    for (const c of CALIBERS) {
      const n = count(tpl(), c.re);
      if (n !== c.want) bad.push(`「${c.name}」${n} 次 ≠ ${c.want}`);
    }
    expect(bad, '唯一出现被破坏（新增了第二处正句；应改为引用）').toEqual([]);
  });

  it('题类自洽⑤⑥已删除（纯引用＋元话语自指；判据本体单源在作答位条款）', () => {
    const t = tpl();
    // 🔴 2026-10-11（T13·G101）：原锁要求"⑥ 须为引用式（含'判据见作答位条款，此处不另立'）"——该括注是**元话语自指**，
    //   且属主 §八 明确"引用对模型是噪音、应在注入时展开为空"；就地复述又会成**第二处正句** ⇒ **⑤⑥ 整条删除**。
    expect(t, 'G101：⑤⑥ 引用式条目已删（元话语不得回潮）').not.toContain('判据见作答位条款，此处不另立');
    expect(t, 'G101：⑤ 条已删').not.toContain('⑤同性质');
    expect(t, 'G101：⑥ 条已删').not.toContain('⑥同一题内同性质作答载体形态一致');
    // 判据本体仍在（作答位条款）——单源不丢
    expect(t, '判据本体（作答位条款）仍在').toContain('不得再在题后另起同性质的整行短答载体');
  });
});
