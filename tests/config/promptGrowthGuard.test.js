// 🔒 指令"只增不扩"守卫（2026-09-30 用户裁定：# 一条要求越长越难被遵守，段越长越会被跳过）
// ============================================================
// 背景：修复史审计发现"每发现一个缺陷，就在原句上再加一层定语/括注"→ 单条越滚越长（实测最长单条 2073 字），
//   叠加"覆盖式改写"（旧句有效内容被新句盖掉）→ 恶性循环。
// 本守卫先**止住增长**（不改任何内容、不缩任何条款），锁三件事：
//   ① 单条字数上限（= 当前基线，只减不增）；
//   ② 同义判据的"条数指纹"（同一判据跨多条各写一遍的处数，只减不增）；
//   ③ 声明↔实给单源句仍是一定义两消费（防再次被覆盖式改写）。
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { getPromptTemplate, DECLARATION_TRUTH_CLAUSE } from '../../src/config/promptLibrary.js';

const ROOT = path.resolve(__dirname, '../..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const tpl = (g, s = '语文', st = 'primary_low') => getPromptTemplate({ grade: st, subject: s, genType: g }).template;

/** 单条上限（字数）——基线取 2026-09-30 实测最长条（题目自洽①–⑰，2073 字），留 6% 余量；只减不增 */
const MAX_CLAUSE_CHARS = 2200;
/** 同义判据指纹上限：关键词（按正则判，防子串误命中，如「同一题」不得命中「同一题号」）→ 允许出现的"条"数上限
 *  🔴 2026-10-01（结构清晰·口径区分）：本指纹计"**含该关键词的条数**"——它同时罩住两件事：
 *    ① **同一判据跨多条重复表述**（要收口，本指纹的主 targets）；② **同一主题的分点拆解**（大级／小级／例外／序号
 *    各一条，是**不同的事**，属结构清晰、不是同义多套）。用户 2026-10-01 定"结构清晰"后，②会正当抬高计数，
 *    故「分值」5→6（分值现分 4 条 + 另有 2 条提及）；判①仍靠 ①②两条 + intraRequestDuplicate 台账管。 */
const DUP_BUDGET = { 分值: 7, 同性质: 5, '同一题(?!号)': 4, 逐题: 4, 账目: 3, 书写载体: 3, 不得省略: 2, 自查: 2 };

// 🔴 2026-10-01（结构清晰·度量改准）：原只把 `\n·` / `\n【` 认作"条"——于是【题目自洽①–⑰】
//    （17 项**逐行编号**）被算作**一条 2073 字**（假象）。现把 `\n①–⑳` 也认作条界，使度量与
//    "每条可独立核对"一致（该块真实的最长条 ~250 字，远低于上限）。
// 🔴 2026-10-04（拆条度量改准）：**结构标记不算内容字数**——条首 `· ` 是"一条一行"的排版标记，
//   非判据内容。守卫本意是"内容只减不增"（见 line 38-39："只拆不加字 → 放行"），
//   但原实现把 `· ` 计入 → 任何"一条多事→拆多条"都会因新增标记被抓（与"拆条正是要的结构清晰"自相矛盾）。
//   故在此剥掉条首 `· `（不影响关键词指纹与单条上限的判定语义）。留痕：#1 正式考卷批 L2–L5 拆条。
const clausesOf = (t) => t.split(/\n(?=·|【|①|②|③|④|⑤|⑥|⑦|⑧|⑨|⑩|⑪|⑫|⑬|⑭|⑮|⑯|⑰|⑱|⑲|⑳)/).map((s) => s.trim().replace(/^·\s*/, '')).filter((s) => s.length > 12);

describe('指令"只增不扩"守卫（止住越滚越长）', () => {
  it('总字数只减不增（条数不设上限——拆"一条多事"正是要的结构清晰）', () => {
    // 🔴 2026-10-01（重洗牌·度量改准 + 结构拆分）：计数器把 `\n①–⑳` 也认作条（【题目自洽①–⑰】的 17 项本就逐行独立）。
    // 🔴 2026-10-02（逐条复核·B1–B5）：exam 导语删与【任务】行重复的括注、创作要求 1 删失指向括注、【卷面结构】说明移为块内首条、
    //    "共X题"拆出、exam 创作要求条 7 拆为 7/8/9 → 总字数继续下调（9277/10133）。
    // 🔴 2026-10-02（用户裁定·**取消条数上限**）：条数不是质量指标——"一条多事"拆成两条各说一事，正是本次要的**结构清晰**，
    //    卡条数会把拆分当成"增长"而挡住。真正的闸门是**总字数**（守卫本意"一条越长越难遵守/段越长越被跳过"由字数管），
    //    且**只减不增**：拆分若同时加字，会在总字数上被抓；只拆不加字 → 放行。单条字数上限另由下一用例管。
    // 🔴 2026-10-02（遗留问题·质量底线解锁重写 + 题目自洽①拆出）：【质量底线】9 条→16 条（同义半句合并、元话语删）、
    //    题目自洽① 从块标题行拆出 → 条数 83→90（不再受条数管），**总字数 9277→9090 / 10133→9946（继续下调）**。
    // 🔴 2026-10-03（①三维度·门控缺口补做·用户授权"锁可先解开、改完再锁"）：**line 载体位置条款**（"整行书写横线
    //    只在整题之后集中给一处、不插在要求/提示分条之间"）原**只写在英语分支**，语文（及其他 line 载体学科）缺此判据 →
    //    实测伤情⑤（低段写话"要求(1)(2)(3)"分条之间被插入满行横线）。处置＝把该**既有判据**提为 line 载体通用（非新增约束、
    //    属"该出现却没出现"的补位）→ 语文侧 +≈130 字。基线按实测**改准**：exam|语文 9090→9199（数学为 blank-area、未变）。
    // 🔴 2026-10-04（真实生成七问题根治·解锁改准）：exam|语文 净增 ≈60 字，来自**四处根因判据**（判据未删、无枚举）：
    //    ①【卷面结构】大类行示例带分值＋明写"大类行须写出本大类总分"（修 issue 3/4）；② 分值说明改**判据式**
    //    "形式由计分口径定"（去枚举，修 issue 2）；③【质量底线】"不重复设题"扩到"分设两栏的同型题、同型并入一栏"（修 issue 1b）；
    //    ④【卷面自洽】补"大题标题须与其下小题的实际作答方式相符"（修 issue 5）。同批已把分值条示例删短（净减）。
    // 🔴 2026-10-04（1a/6 模型侧加强·解锁改准）：作答位条款再 +≈62 字（各题类同增，因该条款全题类注入、内容型不注入）：
    //    ⑤"材料内缺内容处就地留空"由长句**拆成独立一条**（1a：选字/选词缺字处没留空）；⑥ 形态判据补"同一题内各空按
    //    各自所填内容分别定形、可并存"（6：七/八/九 短答误用括号空位；同时防"一律横线"的一刀切）。
    // 🔴 2026-10-04（①就地挖空·解锁改准）：读拼音写词语 clause 补"在原句中的位置就地留空"（+≈22）——上版漏此半句，
    //    模型把词留在句里、拼音格子甩到末尾（12:58 产物回归）。
    // 🔴 2026-10-10（用户裁定·分值标注含单价·解锁改准）：分值条由「大题标题只写总分」改为
    //    「全大题同一单价时含单价（写大题标题·量词用占位）、各题分值不一时只写总分并逐题标」（消"单价无家可归
    //    →模型造'1.＋题干'承载"的相抵）。同批**两处同义收口**（删 :453 与 :423 逐字重复的"（同型并列算一题）"−12；
    //    删 :453 与次句语义重复的"（大题级必标；题级按需）"−13）⇒ **语文净 0（回到原帽）**；数学侧反低于原帽、未动。
    // 🔴 2026-10-10（〔322〕"题目标题须作答方式"统一判据·解锁改准）：原"作答方式"要求散在 大题(小学)/小题(条件)/组标题(教辅)
    //    三处、且中学留"先说做什么"宽泛口子 ⇒ 新增**一条统一正句**（凡题目标题不论哪一层都须点明实际作答方式；
    //    **课标内容领域名／大类名**例外——用项目既有术语，避免"新概念"），并删中学分支"先说做什么"与"（再说怎么做或选什么）"。
    //    该条为 exam 通用（语文/数学同源）。
    //    🔴 2026-10-10（〔328〕三口径闭环）：新增**计分对象口径单源条**（与编号对象口径为姊妹条）＝+85；
    //    同批删"账目里的题量按上条口径计"（−14）与账目"计数按编号对象口径"改"计分对象"（−2）。
    //    🔴 2026-10-10（〔330〕标注位置封歧义＋计分对象改"自证等式"）：分值条补"位置＝该题题干后、不标在作答载体旁"（+40）。
    //    🔴 2026-10-10（〔331〕计分对象补"判分处"锚）：原自证等式只保证数一致、未给"挑哪个单位"的锚 ⇒ 补锚（+33）。
    //    🔴 2026-10-10（〔333〕三角度自查·H1 计量不匹配）：② 由"各计分对象分值不一"改**题级**并写明所指（＝各题的计分对象数×单价不等，+15）。
    //    🔴 2026-10-10（〔342〕产物实证两真缺）：QOC 补"仅换情境/材料包装的同类小题仍属同一要求"（判据可自判）＋计分对象补"单价单位须与实际判分处一致"。
    // 🔴 2026-10-10（〔346〕产物实证四根因·解锁改准）：四处**根因判据**（判据未删、无枚举、无题型名）——
    //    ① QOC"全大题仅一个小题时"不可自判（模型把并列算式当多小题）⇒ 改"整大题只含一个编号对象时（＝共用一条作答要求，哪怕并列多少项）"（治"1. 直接写出得数。"＋游园会 2.3.4.5 硬编号）；
    //    ② 大题标题命名补"只写一个空泛的类别名不算点明作答方式"（治"四、判断"无作答方式）；
    //    ③ 小学段大题标题补自判句"删去情境词后须仍是完整的作答要求"（治"一、游园会'识字加油站'：读拼音写词语"情境包装标题）；
    //    ④ 数学 layoutSpec 竖式条补"多个算式同一行横向并排、不逐式各占一整段"（治竖式题竖向堆叠）。
    //    ⇒ exam|语文 +119、exam|数学 +152（①②exam 通用，③④分支各命中一支）；题集类各 +≈40（①QOC 全题类注入）。
    //    ⑤【卷面自洽】"不另起同文题干"同用旧锚"全大题仅一个小题时"⇒ 一并改准（同锚不同事，+24）。
    // 🔴 2026-10-10（〔347〕促规范·减约束·基线下调）：删逆序句/整除要求/同义复述，exam 语文 -212、数学 -212。
    // 🔴 2026-10-10（〔348〕情境条去"另起一行"＋去否定式并置·基线下调）：exam 语文 -43、数学 -43（情境条仅 exam）。
    // 🔴 2026-10-11（属主·自洽体检·基线按实测改准）：作答位条款**新增两条正向判据**
    //   （"线索句里待答内容处本就是空位"＋"题干或材料里挖空的题：挖空之处就地给出载体"）→ exam 两类各 +149 字。
    const cap = { 'exam|语文': 9823, 'exam|数学': 10481 };
    const over = [];
    for (const [k, n0] of Object.entries(cap)) {
      const [g, s] = k.split('|');
      const items = clausesOf(tpl(g, s));
      const n = items.reduce((a, x) => a + x.length, 0);
      if (n > n0) over.push(`${k} 总字数 ${n} > ${n0}`);
    }
    expect(over, '新增条款必须同时删/并旧条（总字数只减不增）').toEqual([]);
  });

  // 🔴 2026-10-03（用户裁定·Q4"补题集类字数守卫"）：原守卫只锁 exam 两类，**题集/内容类无闸门**——
  //    前几轮修复若只在教辅侧叠加条款，总字数照样能涨而不被拦。本条按 exam 同款口径锁 8 类（语文·primary_low，
  //    取向B 删"以相同深度"后实测基线）；只减不增。新增条款必须同时删/并旧条，防"打补丁叠加"回潮。
  it('题集/内容类总字数只减不增（与 exam 同款闸门，防教辅侧堆量）', () => {
    // 🔴 2026-10-03（①三维度·门控缺口补做）：同 exam——line 载体位置条款提为通用，语文侧 8 类各 +≈130 字，基线按实测改准。
    // 2026-10-03（内容型"作答位"口径改准·最终方案）：内容型**仍不注入题类格式块**（三方审计：类型不串味），
    //   改由**修正创作要求里的引用指向**（"按本学科本学段的作答载体规格"→"见【输出格式】的作答位条款"）解决空指向 →
    //   内容型字数不增，基线维持。（曾一度按"注入载体规格"改准，因撞类型不串味审计而回退。）
    //    ⑤/⑥ 同 exam（作答位条款全题类注入）→ 各题类 +≈62 字，基线按实测改准。
    // 🔴 2026-10-10（〔347〕促规范·减约束·基线下调）：分值标注条与自洽条收口，各题类按实测下调（practice -2 … errorbook -90）。
    // 🔴 2026-10-11（属主·自洽体检·基线按实测改准）：同上两条作答位新增判据 → 各题类随之 +93
    //   （errorbook 另因错题本变式条改动 +195）。
    const capT = {
      practice: 7652, special: 7629, preview: 3219, reading: 7641,
      summary: 3308, dictation: 7528, errorbook: 7022, review: 7560,
    };
    const over = [];
    for (const [g, n0] of Object.entries(capT)) {
      const n = clausesOf(tpl(g)).reduce((a, x) => a + x.length, 0);
      if (n > n0) over.push(`${g} 总字数 ${n} > ${n0}`);
    }
    expect(over, '题集/内容类新增条款必须同时删/并旧条（总字数只减不增）').toEqual([]);
  });

  it('单条字数不得超过基线（只减不增）', () => {
    const bad = [];
    for (const g of ['exam', 'practice', 'summary', 'preview', 'reading', 'dictation', 'errorbook', 'review', 'special']) {
      for (const cl of clausesOf(tpl(g))) if (cl.length > MAX_CLAUSE_CHARS) bad.push(`${g}: ${cl.length} 字 → ${cl.slice(0, 24)}`);
    }
    expect(bad.slice(0, 5), `以下单条超上限（${MAX_CLAUSE_CHARS} 字）`).toEqual([]);
  });

  it('同义判据的条数指纹不得增加（同一判据跨多条各写一遍 = 同义多套）', () => {
    const items = clausesOf(tpl('exam'));
    const over = [];
    for (const [k, cap] of Object.entries(DUP_BUDGET)) {
      const re = new RegExp(k);
      const n = items.filter((x) => re.test(x)).length;
      if (n > cap) over.push(`「${k}」${n} 条 > 上限 ${cap}`);
    }
    expect(over, '同义判据条数增加（新增即需收口或走单源）').toEqual([]);
  });

  it('声明↔实给单源句不被覆盖式改写：一定义两消费，且旧实例仍在', () => {
    const lib = read('src/config/promptLibrary.js');
    expect((lib.match(/export const DECLARATION_TRUTH_CLAUSE/g) || []).length).toBe(1);
    expect((lib.match(/DECLARATION_TRUTH_CLAUSE/g) || []).length).toBe(3);
    expect(DECLARATION_TRUTH_CLAUSE, '旧句实例不得被新句盖掉').toContain('拼音、首字母、提示词、图、表、数据、待选项');
  });
});
