// S3′·③ **逐格八问留痕**（方法文件 §十一）：每个"情形格"过一遍八问（①三维度／②课标／③啰嗦／④精准／
//   ⑤诱导／⑥拼接／⑦排序／⑧质量），逐格给 过／不适用／不过（已处置）＋**判定层级**。
//   表达＝**基准行 ＋ 覆盖行**（与"默认＋例外"同义）：基准行＝"有判据源"的标准格；覆盖行＝①无判据源格
//   （全"不适用"）②**引课标**格 ③**曾不过·已处置**格。**每格 8 条全落点，不得跳问**。
// ============================================================
const Q8 = ['①三维度', '②课标', '③啰嗦', '④精准', '⑤诱导', '⑥拼接', '⑦排序', '⑧质量'];
/** 每问的**判定层级**（⑧明规则：无真机通道，须标层级，禁止无依据断言） */
const Q8_LAYER = ['程序校验', '纸面推演', '程序校验＋纸面', '纸面推演', '程序校验', '程序校验', '程序校验', '纸面＋程序（**无真机通道**）'];
/** 基准行：有判据源的标准格（①该条属本"类型×学段×学科"；②判据句不引课标；③～⑦守卫已绿；⑧见层级） */
const Q8_BASE = ['过', '不', '过', '过', '过', '过', '过', '过'];
/** 无判据源格：全不适用（该情形由程序侧承载或自然不发生——见 §5.6） */
const Q8_NOSRC = ['不', '不', '不', '不', '不', '不', '不', '不'];
/** 覆盖行（替换基准行中的某一问；`q`＝问序号 0..7） */
const Q8_OVERRIDE = [
  { face: 'C6', sc: '材料通道（全文 full ／ 锚清单 anchor）与来源约定', q: 1, v: '过',
    why: '判据句引"可依本学段课标学业要求"——课标引用受控（附条 8：蓝图库两表 10/10 带 source 的**全量锁**已绿）' },
  { face: 'C9', sc: '教材版本口径（术语写法／册次／是否已学）', q: 1, v: '过',
    why: '判据句以**教材版本**为准、不冒称课标（口径不混用，符合附条 8"不得两套口径并行"）' },
  { face: 'C7', sc: '正式卷：大类名↔大题标题 与其下各题内容相符', q: 3, v: '处',
    why: '**T20·①** 补"遮住该名称、只看其下各题——能否据此反推出该名称"判法（原"相符"不可判）' },
  { face: 'C8', sc: '同栏／同型不重复设栏（按考查作用判重）', q: 3, v: '处',
    why: '**T20·②** 豁免加**管辖域**（"在同一大题、同一层内"），并补"跨大题或跨层复现同一知识点时不得同型同法"' },
  { face: 'C8', sc: '同题内并列设问不雷同（并列对照设问除外）', q: 3, v: '处',
    why: '**T20·②** 同批改准（豁免有边界、判据可判）' },
  { face: 'Z2', sc: '内容型：作答位紧随其题、在设问之后（有选项时在选项行之前）', q: 3, v: '处',
    why: '**S0 属主裁定"要覆盖"** 后新增 `carrierPlacement`（内容型原无位置判据）' },
  { face: 'Z2', sc: '材料内缺处：待答之处＝空位之处＝载体之处，载体紧随该空位', q: 3, v: '处',
    why: '内容型部分由 **S0** 的 `carrierPlacement`（"材料中缺处就地留空"）补齐（题类判据原已在位）' },
  { face: 'Z3', sc: '内容型：题面声明的作答形态／数量／用具一律照声明给到', q: 3, v: '处',
    why: '**S0** 新增 `carrierPlacement`（内容型原无"题面声明→载体照给"判据）' },
];

/** 有效八问行（基准 ＋ 覆盖 ／ 无判据源格＝全不适用） */
function q8Effective(f) {
  return f.items.map((it) => {
    const hasSrc = Array.isArray(it.src) && it.src.length > 0;
    const row = (hasSrc ? Q8_BASE : Q8_NOSRC).slice();
    const ov = Q8_OVERRIDE.filter((o) => o.face === f.face && o.sc === it.sc);
    for (const o of ov) row[o.q] = o.v;
    return { face: f.face, sc: it.sc, row, ov };
  });
}
const q8Rows = SCENARIOS.flatMap(q8Effective);

describe('S3′·③ 逐格八问留痕（每格 8 条全落点，不得跳问）', () => {
  it('八问名目与层级齐备（8×8）', () => {
    expect(Q8).toHaveLength(8);
    expect(Q8_LAYER).toHaveLength(8);
  });

  it('每格恰 8 条、取值∈{过／不／处}，且"处"必带已处置依据（事务号/裁定）', () => {
    const bad = [];
    for (const r of q8Rows) {
      if (r.row.length !== 8) bad.push(`${r.face}·${r.sc} 条数=${r.row.length}`);
      r.row.forEach((v, i) => {
        if (!['过', '不', '处'].includes(v)) bad.push(`${r.face}·${r.sc}·${Q8[i]} 取值异常=${v}`);
        if (v === '处') {
          const o = r.ov.find((x) => x.q === i);
          if (!o || !/T\d|S0|裁定/.test(String(o.why))) bad.push(`${r.face}·${r.sc}·${Q8[i]} "已处置"未指向事务号/裁定`);
        }
      });
    }
    expect(bad, `八问留痕异常：\n${bad.join('\n')}`).toEqual([]);
  });

  it('覆盖行必须真落在既有情形格上（防写错 face／sc 导致"静默不生效"）', () => {
    const cells = new Set(q8Rows.map((r) => `${r.face}·${r.sc}`));
    const bad = Q8_OVERRIDE.filter((o) => !cells.has(`${o.face}·${o.sc}`)).map((o) => `${o.face}·${o.sc}`);
    expect(bad, `覆盖行指向了不存在的情形格：\n${bad.join('\n')}`).toEqual([]);
  });

  it('判定层级不得留空（⑧ 无真机通道 ⇒ 须标层级，禁止无依据断言）', () => {
    expect(Q8_LAYER.filter((x) => !String(x).trim())).toEqual([]);
  });

  it('直方图被钉死（防"悄悄改判"式假绿）', () => {
    const hist = { 过: 0, 不: 0, 处: 0 };
    for (const r of q8Rows) for (const v of r.row) hist[v] += 1;
    expect(q8Rows.length).toBe(70);
    expect(hist).toEqual({ 过: 430, 不: 124, 处: 6 });
    expect(q8Rows.length * 8).toBe(560);
  });
});

