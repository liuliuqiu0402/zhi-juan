/**
 * 🔬 覆盖判定分类（Coverage Probe）—— 对账器"出现度判定"的确定性分类单一事实源
 * ============================================================
 * 🔴 定位（2026-09 覆盖治理 P2·根治）：practice/知识型正文是"情境化题目 + 答案"，核心知识多以行为/技能形态呈现，
 *    考点原文词（尤其"XX的意义/方法/规律/应用"类）不会逐字出现在正文——此前按考点词面逐词判定
 *    导致对账器大面积误报（曾以"小数乘法和除法"课时练出现 18/18 全缺漏，实为 78% 误报）。
 * 术语约定（2026-09 全局统一）：本文档中"考点/锚考点/考点名"均指知识层级树（大概念 → 核心知识 coreKnowledge
 *    → 具体概念）的 coreKnowledge 条目——与注入给模型/用户可见文案的"核心知识"措辞同义；"考点"仅在
 *    试卷类（exam）命题语境与代码注释内部出现，非覆盖对象术语。
 *
 * 判定两级（全部确定性，不语义理解；方向"宁可漏报不缺报"，防误报）：
 *   - chapter（章级聚合）：考点名含"行为/技能引导词"（意义/方法/规律/应用/取值…）→ 正文以行为体现，
 *     无法用词面可靠判定，归入章级——该章有任一考点命中即视为该章行为考点族已覆盖。
 *   - literal（精确判定）：概念/术词专名（如 循环小数/质数/方程…）→ 正文须以概念词出现，
 *     用 考点名+下位概念(+必要等价词) 词面命中判定；未命中即报缺（含"必须原词出现的概念"漏检）。
 *
 * 判缺产出两类，供调用方分层处置：
 *   - missing          : literal 考点未命中（有具体名，可由 auto 补漏指名短生成）
 *   - missingChapters  : 整章零命中的章（章级提示；行为考点不逐条报，防诱导）
 * ============================================================
 */

/** 行为语义引导词：考点名含其一 → 章级聚合（正文以行为/情境体现，考点名整串不会逐字出现） */
export const BEHAVIOR_TERMS = [
  '意义', '方法', '规律', '应用', '取值', '算法', '算理', '换算', '估算', '理解',
  '比较', '转化', '判断', '探究', '解决', '联系', '推理', '归纳', '分类',
  '运用', '掌握', '建模', '迁移', '思路', '步骤', '依据',
  '竖式', '计算', '列式', '运算',
];

/** 技能操作引导词（2026-09 章级聚合全局归并）：各学科"做什么"的动词/操作考点——
 *  语文（朗读/默读/背诵/赏析/体会…）、英语（认读/抄写/复述…）、科学（观察/实验/测量/记录…）、
 *  理化（实验/操作/检验…）、体音美（演唱/演奏/创作/绘制…）等——
 *  概念专名（循环小数/质数/朝代/时态/电压/细胞…）不落此组，不会误放行。 */
export const SKILL_TERMS = [
  '赏析', '鉴赏', '体会', '感悟', '感受', '聆听', '欣赏', '演唱', '演奏', '绘制', '绘画',
  '朗读', '默读', '背诵', '抄写', '仿写', '复述', '创作', '写话', '观察', '实验', '测量',
  '记录', '操作', '评价', '预测', '验证', '设计', '制作', '筛选', '提取', '整理',
];

/** 考查方面/问法尾词（2026-09 章级聚合全局归并）：考点名以"XX的特征/影响/做法…"命名时，
 *  正文以"说一说…特点是/作用是…"等行为呈现、不逐字出现考点名 → 章级聚合；
 *  具体概念名（"下定义的说明方法""列数字""呼吸作用""商品的价值"）不带这些尾词 → 仍精确判定（防概念漏报）。
 *  🔧 词形校准：'作用'/'价值' 与概念术语高频共现（光合作用/呼吸作用/商品的价值/价值观）——
 *    改用 '的作用'（"…的作用"问法形态）避免把生物/政治概念误放行（2026-09 护栏实证）。 */
export const ASPECT_TERMS = [
  '特征', '影响', '启示', '做法', '成因', '过程', '读法', '写法', '用法', '顺序', '的作用',
];

/** 全部章级引导词（classifyProbe 判定用并集） */
export const CHAPTER_TERMS = [...new Set([...BEHAVIOR_TERMS, ...SKILL_TERMS, ...ASPECT_TERMS])];

/** 数值近似族等价检测词（"积/商的近似值"正文常写作"保留X位小数/四舍五入/约"，词面收敛用）
 *  🔧 2026-09 实证校准：等价词须用 ≥4 字长锚——wordMatch 对 <4 字关键词做"汉字边界"检查，
 *    短词（保留/约）嵌于句中（"得数保留两位小数"）两侧为汉字 → 恒不命中 → 积/商的近似值误报缺漏；
 *    长锚（保留两位/保留整数…）走 includes 直接命中，与"保留X位小数"真实呈现对齐 */
export const APPROX_ALIAS = ['近似值', '四舍五入', '保留整数', '保留一位', '保留两位', '保留三位', '保留四位'];

/**
 * 判定考点属"章级聚合"还是"精确判定"。
 * @param {String} name 考点名
 * @returns {'chapter'|'literal'}
 */
export const classifyProbe = (name = '') =>
  CHAPTER_TERMS.some((t) => name.includes(t)) ? 'chapter' : 'literal';

/** 是否数值近似族（判定时附等价词，收敛"保留X位小数/四舍五入/约"措辞演化） */
const isApprox = (name = '') => /近似|估算/.test(name);

/** literal 考点的判定词集合（考点名 + 下位概念 + 必要等价词），供对账器 wordMatch */
export const literalProbeWords = (anchor = {}) => {
  const name = anchor?.name || '';
  const words = [name, ...(anchor?.specificConcepts || [])]
    .filter((w) => w && w.length >= 2);
  if (isApprox(name)) words.push(...APPROX_ALIAS);
  return [...new Set(words)];
};

/** 分组：章 → [{anchor}]（跳过 missing 缺料锚，红线不进可命题清单） */
export const groupByChapter = (anchors = []) => {
  const map = new Map();
  for (const a of (anchors || [])) {
    if (a.bind?.status === 'missing') continue;
    const k = a.chapterTitle || '未标注章节';
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(a);
  }
  return map;
};