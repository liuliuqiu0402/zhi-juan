  const keys = (Array.isArray(domainKeys) ? domainKeys : [domainKeys]).filter(Boolean).slice(0, SPECIAL_DOMAIN_MAX);
  return keys.map((k) => resolveSpecialDomain(subject, stageKey, k)).filter(Boolean);
