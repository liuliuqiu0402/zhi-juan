/**
 * 按类别查询分析阶段 Prompt（行为与旧 getMatchingBlockInstructions 对齐）
 * @param {{category: string, id?: string}} options
 * @returns {Array} 匹配的 prompt 列表
 */
export function getAnalysisPrompts({ category = '', id = '' } = {}) {
  return ANALYSIS_PROMPTS.filter(p =>
    (!category || p.category === category) &&
    (!id || p.id === id)
  );
}

