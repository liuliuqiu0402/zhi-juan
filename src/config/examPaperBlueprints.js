/** 学科名模糊匹配兜底表（教材库学科名 → 蓝本 key 学科名） */
const SUBJECT_ALIAS = {
  '政治': '道德与法治', '思想品德': '道德与法治', '道法': '道德与法治',
  '信息技术': '信息科技', '信息': '信息科技',
  '科学（小学）': '科学', '小学科学': '科学',
};

/** 学段兜底链：无精确匹配时依次降级 */
const STAGE_FALLBACK = {
  primary_low: ['primary_mid', 'primary_high', 'middle'],
  primary_mid: ['primary_high', 'primary_low', 'middle'],
  primary_high: ['primary_mid', 'middle'],
  middle: ['high', 'primary_high'],
  high: ['middle'],
};

/** 学科-学段联合别名：同一门课程在不同学段名称不同（道德与法治课在高中叫思想政治） */
const STAGE_SUBJECT_ALIAS = {
  '道德与法治|high': '思想政治|high',
  '思想政治|primary_low': '道德与法治|primary_low',
  '思想政治|primary_mid': '道德与法治|primary_mid',
  '思想政治|primary_high': '道德与法治|primary_high',
  '思想政治|middle': '道德与法治|middle',
};

/**
 * 查询真题卷蓝本
 * @param {string} subject 学科名（未标准化也可）
 * @param {string} stage primary_low/primary_mid/primary_high/middle/high
 * @returns {{label:string, fullScore:number, duration:string, sections:Array, key:string}|null}
 */
export function getExamBlueprint(subject, stage) {
  if (!subject || !stage) return null;
  const stdSubject = SUBJECT_ALIAS[subject] || subject;
  // 学段联合别名（同一课程跨学段名称转换，如高中道法→思想政治）
  const joint = STAGE_SUBJECT_ALIAS[`${stdSubject}|${stage}`] || `${stdSubject}|${stage}`;
  const [bpSubject, bpStage] = joint.split('|');
  const direct = EXAM_BLUEPRINTS[`${bpSubject}|${bpStage}`];
  if (direct) return { ...direct, key: `${bpSubject}|${bpStage}`, subject: bpSubject, stage: bpStage };
  // 学段降级链
  const chain = STAGE_FALLBACK[bpStage] || [];
  for (const st of chain) {
    const bp = EXAM_BLUEPRINTS[`${bpSubject}|${st}`];
    if (bp) return { ...bp, key: `${bpSubject}|${st}`, subject: bpSubject, stage: bpStage };
  }
  // 全学段通配蓝本（如信息科技跨学段通用）
  const all = EXAM_BLUEPRINTS[`${bpSubject}|all`];
  if (all) return { ...all, key: `${bpSubject}|all`, subject: bpSubject, stage: bpStage };
  return null;
}

/**
 * 构建注入生成 prompt 的真题蓝本文本
 * @param {object} bp 蓝本对象（getExamBlueprint 返回值）
 */
export function buildExamBlueprintText(bp) {
  if (!bp) return '';
  const layout = EXAM_PAPER_LAYOUT
    .replace(/\{duration\}/g, bp.duration)
    .replace(/\{fullScore\}/g, String(bp.fullScore));
  const sectionsText = bp.sections
    .map((s, i) => {
      const no = '一二三四五六七八九十'[i] || String(i + 1);
      return `${no}、${s.name}。（${s.score}分）——${s.note}`;
    })
    .join('\n');
  const stageKey = String(bp.stage || (bp.key || '').split('|')[1] || 'middle');
  const stageGroup = stageKey.startsWith('primary') ? 'primary'
    : stageKey === 'middle' ? 'middle'
    : stageKey === 'high' ? 'high' : 'middle';
  const stageBlock = EXAM_STAGE_STANDARDS[stageGroup]
    ? `\n▌${EXAM_STAGE_LABELS[stageGroup]}命题要求\n${EXAM_STAGE_STANDARDS[stageGroup]}`
    : '';
  const subjectBlock = EXAM_SUBJECT_STANDARDS[bp.subject]
    ? `\n▌${bp.subject}命题要求\n${EXAM_SUBJECT_STANDARDS[bp.subject]}`
    : '';
  return `【真题卷结构蓝本——${bp.label}（满分${bp.fullScore}分，考试时间${bp.duration}）】
🔴 本蓝本为新课标真题卷通行规范，题型骨架、大题名称、分值、顺序必须严格遵循，不得增删大题、不得创意命名题型（禁止"小达人""闯关""对对碰""大转盘"等说法）、不得改动分值。
▌卷面规范
${layout}
▌题型骨架（大题分值之和=${bp.fullScore}分）
${sectionsText}
▌新课标命题要求（通用）
${EXAM_NEW_STANDARD}${stageBlock}${subjectBlock}
▌灵活性边界：仅允许在"各答题内的小题数量、小题分值分配、考点选材"上根据本次教材内容适配；大题序列与分值不可变。`;
}

export default {
  EXAM_BLUEPRINTS,
  EXAM_PAPER_LAYOUT,
  EXAM_NEW_STANDARD,
  EXAM_STAGE_STANDARDS,
  EXAM_STAGE_LABELS,
  EXAM_SUBJECT_STANDARDS,
  getExamBlueprint,
  buildExamBlueprintText,
};
