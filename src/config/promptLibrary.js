/** 全部资料类型键（与 TYPE_BASES 一致） */
const ALL_GEN_TYPES = Object.keys(TYPE_BASES);

// 🔴 三维度 cell 预生成（学段×学科×类型，仅实际开设组合；一条全貌 = 类型基础 + 学科×学段要点 + 学段特点）
