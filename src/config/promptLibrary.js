/** 规范块：**不可被旧自定义模板覆盖**（块标题）。分值/编号是单一开关，用户模板若存的是旧版，
 *  内置判据会整份被挤掉（2026-10-24 真机"全卷不标任何分"即此因）。
 *  · 【卷首】：正式卷卷首固定结构（标题→时间行→密封线→导语→第一大题）的**唯一来源**；
 *    短自定义模板缺该块时模型收不到顺序条款，产物卷首结构消失（2026-10-24 真机）。故**必并入**。
 *  · 【分值标注】：**必并入**（模板没有该块时插到【输出格式】之前）。
 *  · 【卷面结构】：块头"参考分值只是份量参考"与分值契约同源——旧版写"不是标题里要填的数字"
 *    与单一开关相抵（模型读到"标题不填分"⇒ 全卷不标分）。**模板已有该块时整块换成内置现行版**；
 *    短自定义模板没有此块则不插入（不把整段结构说明塞进用户短文）。 */
const NORMATIVE_BLOCKS = [
  { title: '卷首', insertIfMissing: true, insertBefore: ['卷面层级', '分值标注', '输出格式'] },
  // requireMarker：用户块里连 {structure} 占位符都没有，说明是另一套自定义块、不是内置旧版的副本——不动它。
  { title: '卷面结构', insertIfMissing: false, requireMarker: '{structure}' },
  { title: '分值标注', legacyTitle: '编号与分值', insertIfMissing: true },
];

/** 🔴 旧块名迁移（2026-10-24 真机"卷首结构消失＋整卷不标分"）：4326eeb 前把卷首/层级/自洽/情境/分值
 *  全部写在**一个【卷面格式】块**里，之后才拆成独立块。用户模板若存的是旧版，该块原样保留 ⇒
 *  ① 新【分值标注】与旧块"例外：同型客观小题…小题后不再逐个标"**相抵**，模型按旧口子整卷不标分；
 *  ② 大题行无分 ⇒ 渲染侧 `parseExamSections` 认不出大题 ⇒ 注意事项/题号得分表（卷首固定结构）整体不注入。
 *  处置：含旧版特征（"卷首固定顺序"）的【卷面格式】块**整段删除**，再按现行拆分块补入（缺哪块补哪块）。 */
const LEGACY_FORMAT_BLOCK = {
  title: '卷面格式',
  marker: '卷首固定顺序',
  expandTo: ['卷首', '卷面层级', '卷面自洽', '情境与页码'],
};

/** 块的起止：**行首**的 `【标题…】`（允许块名带括注，如【卷面结构（依{curriculum}）】）到下一个行首【之前。
 *  🔴 必须锚行首：块内行文会**行内引用**别的块名（如【卷面结构】里写"一律按【分值标注】判"），
 *     不锚行首会把该引用当成块起点、把整块截断（2026-10-24 实测：替换后【卷面结构】只剩尾巴）。 */
const blockRe = (title) => new RegExp(`(?<=\\n|^)【${title}[^】]*】[\\s\\S]*?(?=\\n【|$)`);

/** 取模板中的一个块 */
const extractBlock = (text, title) => {
  const m = String(text || '').match(blockRe(title));
  return m ? m[0].trim() : '';
};

/** 在指定块标题之前插入一块（按候选顺序取第一个存在的锚点；都无则追加到末尾）。
 *  块界统一**恰一空行**（与 blockStructure 守卫同口径）。 */
const insertBlockBefore = (text, blockText, anchors = []) => {
  const s = String(text || '');
  for (const a of anchors) {
    const m = new RegExp(`(?<=\\n|^)【${a}[^】]*】`).exec(s);
    if (!m) continue;
    const head = s.slice(0, m.index).replace(/\s+$/, '');
    const tail = s.slice(m.index);
    return head ? `${head}\n\n${blockText}\n\n${tail}` : `${blockText}\n\n${tail}`;
  }
  return `${s.replace(/\s+$/, '')}\n\n${blockText}`;
};

/** 用内置块替换自定义模板的同块：同名块 → 原地替换；旧块名 → 按旧名替换；无块 → 按需插到锚点前 */
const replaceNormativeBlock = (text, title, blockText, { legacyTitle = '', insertIfMissing = false, requireMarker = '', insertBefore = [] } = {}) => {
  if (!blockText) return text;
  const existing = String(text || '').match(blockRe(title));
  if (existing && requireMarker && !existing[0].includes(requireMarker)) return text;
  // 同名块与旧块名并存时（旧模板改过名又保留了旧段）：旧段一律清掉，不得留下两套判据。
  const stripLegacy = (s) => (legacyTitle
    ? s.replace(blockRe(legacyTitle), '').replace(/\n{3,}/g, '\n\n')
    : s);
  const re = blockRe(title);
  if (re.test(text)) return stripLegacy(text.replace(re, () => blockText));
  if (legacyTitle && blockRe(legacyTitle).test(text)) return text.replace(blockRe(legacyTitle), () => blockText);
  if (!insertIfMissing) return text;
  return insertBlockBefore(text, blockText, insertBefore.length ? insertBefore : ['输出格式']);
};

/** 旧【卷面格式】块（4326eeb 前的单块形态）→ 在原位置展开为现行拆分块。
 *  只在块内含旧版特征时触发：用户自建的同名块（不含该特征）不动。
 *  顺序按内置模板的块序（卷首→卷面层级→卷面自洽→情境与页码），不按插入先后拼。 */
const migrateLegacyFormatBlock = (text, builtin) => {
  const src = String(text || '');
  const m = src.match(blockRe(LEGACY_FORMAT_BLOCK.title));
  if (!m || !m[0].includes(LEGACY_FORMAT_BLOCK.marker)) return src;
  const expansion = LEGACY_FORMAT_BLOCK.expandTo
    .map((t) => extractBlock(builtin, t)).filter(Boolean).join('\n\n');
  if (!expansion) return src;
  const HOLD = '\u0000';
  let out = src.replace(blockRe(LEGACY_FORMAT_BLOCK.title), () => HOLD);
  // 模板若另有同名拆分块（旧块与新版并存）：删掉旧位置之外的，避免展开后重复。
  for (const t of LEGACY_FORMAT_BLOCK.expandTo) out = out.replace(blockRe(t), '');
  out = out.replace(HOLD, () => expansion);
  return out.replace(/\n{3,}/g, '\n\n').replace(/\s+$/, '');
};

/** 用户模板兜底：把内置规范块并入（用户其余自定义原样保留；被并入时返回 `normativeMerged: true` 供日志取证） */
const applyNormativeBlocks = (tpl, { stage = '', subject = '', genType = '' } = {}) => {
  if (!tpl || tpl.source !== 'user' || !tpl.template) return tpl;
  const builtin = BUILTIN_TEMPLATES[`${stage}|${subject}|${genType}`]
    || buildBuiltinTemplate({ stage, subject, genType });
  let merged = tpl.template;
  let changed = false;
  // 旧【卷面格式】单块形态先迁移：不迁走它，旧分值例外句会与新【分值标注】相抵（整卷不标分）。
  // 只对 exam 生效：该块名只出现在 4326eeb 前的正式卷模板里。
  const migrated = genType === 'exam' ? migrateLegacyFormatBlock(merged, builtin) : merged;
  if (migrated !== merged) { merged = migrated; changed = true; }
  for (const spec of NORMATIVE_BLOCKS) {
    // 🔴 2026-10-26（practice 清残留）：【分值标注】只属于正式考卷——教辅不判分，不得并入该块。
    if (spec.title === '分值标注' && genType !== 'exam') continue;
    const block = extractBlock(builtin, spec.title);
    if (!block) continue;
    const next = replaceNormativeBlock(merged, spec.title, block, spec);
    if (next !== merged) { merged = next; changed = true; }
  }
  return changed ? { ...tpl, template: merged, normativeMerged: true } : tpl;
};

/**
 * 三维度匹配指令模板
 * @param {Object} opts { grade(学段键 primary_low 等), subject(规范学科名), genType(资料类型) }
 * @returns {{ id, name, template, source: 'user'|'builtin' }} 未命中返回内置默认（exam 兜底）
 */
export function getPromptTemplate({ grade = '', subject = '', genType = '' }) {
  ensureBuiltinCells(); // 标记能力（工具库开关/自定义契约）变了 → cell 重建（正文点名标记须与实际骨架同源）
  const userLib = loadUserLibrary();
  // 学段键解析唯一事实源：'小学低段/小学中段/小学高段'、一~六年级、初一~初三、高一~高三、初中/高中、五档键 统一走 resolveStageKey
  const stageKeyOf = (grade = '') => {
    if (!grade) return '';
    const key = resolveStageKey(grade);
    return STAGE_KEY_SET.has(key) ? key : '';
  };
  const stageKey = stageKeyOf(grade);
  // 1) 用户精确：grade+subject+genType（停用 → 落下一级）
  const exactId = `${grade}|${subject}|${genType}`;
  if (userLib[exactId]?.template && isLibEntryEnabled('instruction', exactId)) {
    return applyNormativeBlocks({ ...userLib[exactId], id: exactId, source: 'user' }, { stage: stageKey, subject, genType });
  }
  // 2) 用户 subject×genType
  const subjId = `${subject}|${genType}`;
  if (userLib[subjId]?.template && isLibEntryEnabled('instruction', subjId)) {
    return applyNormativeBlocks({ ...userLib[subjId], id: subjId, source: 'user' }, { stage: stageKey, subject, genType });
  }
  // 3) 用户 genType
  if (userLib[genType]?.template && isLibEntryEnabled('instruction', genType)) {
    return applyNormativeBlocks({ ...userLib[genType], id: genType, source: 'user' }, { stage: stageKey, subject, genType });
  }
  // 4) 内置三维度 cell（学段×学科×类型，预生成直取；名称三维度中文；工具库停用该 cell → 落回 5) 学段×类型 模板）
  const cellId = stageKey && subject ? `${stageKey}|${subject}|${genType}` : '';
  const cell = cellId && BUILTIN_TEMPLATES[cellId];
  if (cell && isLibEntryEnabled('instruction', cellId)) {
    return { id: cellId, name: `${STAGE_NAMES[stageKey] || stageKey} · ${subject} · ${GEN_TYPE_NAMES[genType] || genType}`, template: cell, source: 'builtin' };
  }
  // 5) 内置 学段×类型（subject 缺省或该学段未开设该学科时回落）
  if (stageKey) {
    const template = buildBuiltinTemplate({ stage: stageKey, genType });
    return { id: `${stageKey}|${genType}`, name: `${STAGE_NAMES[stageKey] || stageKey} · ${GEN_TYPE_NAMES[genType] || genType}`, template, source: 'builtin' };
  }
  // 6) 内置 genType（类型基础模板兜底）
  const builtin = BUILTIN_TEMPLATES[genType] || BUILTIN_TEMPLATES.exam;
  const name = `内置·${GEN_TYPE_NAMES[genType] || genType}（通用模板）`;
  return { id: genType, name, template: builtin, source: 'builtin' };
}

/**
 * 素材段字面规范化（**通道无关**，保存/导入入口用）：
 *  把硬写的段头（「教材原文」/「教材依据」）与整句说明换成占位符 `{materialHead}` / `{material}`，
 *  使用户库中存的就是通道无关模板。动因（2026-09-14 用户定「编辑器所见即真实注入，不能有歧义」）：
 *  库里若留着硬写段头，编辑器显示的字面就与实际注入不符——入口处一次规范化，库内容与注入口径同构。
 *  幂等：已是占位符的模板原样返回；对空串安全。
 */
export function canonicalizeMaterialPlaceholders(text = '') {
  return String(text || '')
    .split('【教材原文').join('【{materialHead}')
    .split('【教材依据').join('【{materialHead}')
    .split(MATERIAL_HINT.full).join('{material}')
    .split(MATERIAL_HINT.anchor).join('{material}');
}

/** 保存用户模板（genType 维度或三维度精确）
 * ✅ A18：模板先做素材段字面规范化（硬写段头/说明 → 占位符），保证库内容通道无关（库=注入口径同构）。 */
export function savePromptTemplate(key, { name = '', template = '' }) {
  if (!key || !template) return false;
  const lib = loadUserLibrary();
  lib[key] = {
    name,
    template: canonicalizeMaterialPlaceholders(template),
    updatedAt: Date.now(),
  };
  saveUserLibrary(lib);
  return true;
}

/** 删除用户模板 */
export function deletePromptTemplate(key) {
  const lib = loadUserLibrary();
  if (lib[key]) { delete lib[key]; saveUserLibrary(lib); return true; }
  return false;
}

