/**
 * 组装注入指令（最终形态，拼接顺序固定）：
 *  【任务】定位行（系统生成，固定最前）
 *  → 模板正文（指令库模板，占位符替换，用户可排版；学科排版已并入模板本体）
 *  → 【用户附加要求】（最后，优先级最高）
 * 教材原文由生成器在生成时按知识点检索后追加；渲染契约/质检规则/蓝图/教辅结构等附加块
 * 在注入时已并入注入框（用户可见可编辑）。
 * @param {Object} opts { template, grade, subject, unit, genTypeLabel, structure, fullScore, duration, extra }
 * @returns {string} 完整注入指令（注入框展示内容）
 */
export function buildInjectionInstruction(opts = {}) {
  const {
    template = '', grade = '', subject = '', unit = '', genTypeLabel = '',
    structure = '', fullScore = '', duration = '', extra = '', label = '', semester = '', academic = '',
    stage = '', materialChannel = '',
    genType = '', scopeType = '', paperKind = '',
  } = opts;
  // 1) 任务定位行（系统生成，固定最前——模型第一眼知道要干什么）
  const taskLine = `【任务】生成${genTypeLabel || '资料'}：${subject}${grade}${unit ? `·${unit}` : ''}${fullScore ? `（满分${fullScore}分${duration ? `，时长${duration}` : ''}）` : ''}`;
  // 2) 模板正文（占位符替换；{material} 渲染为附加提示——真实素材由生成器按知识点检索后追加）
  let body = String(template || '');
  const map = {
    '{grade}': grade, '{subject}': subject, '{unit}': unit || '本单元', '{scope}': unit || '本单元',
    '{label}': label || genTypeLabel || '试卷', '{semester}': semester || '', '{academic}': academic || '',
    '{structure}': structure || '（按教材内容合理设计大题）',
    '{fullScore}': fullScore, '{duration}': duration,
    // 🔧 课标版本兜底：内置模板已按学段替换（buildBuiltinTemplate），此处覆盖用户自定义模板中的 {curriculum}，
    //   未传学段键时保持通用表述（与历史行为一致）
    '{curriculum}': CURRICULUM_BY_STAGE[stage] || '本学段最新课程标准',
    // 🔧 素材头占位渲染（2026-09-11 极简方案定稿）：教材原文以【压缩原文】随本次委托注入——
    //   素材途径 = 程序按勾选章节直读整章原文 → 压缩（不再有研读轮、不再有 browse 按需取片段）；
    //   该行仅作模板结构提示：本次涉及的内容与材料见开头所列，范围外补充/整合口径见【素材使用约定】。
    //   ✅ A18（2026-09-14 素材通道）：锚清单注入通道下改指【锚点清单】（改"以开头所列知识明细为依据"），
    //      见 MATERIAL_HINT / applyMaterialChannel。
    //   🔒 2026-09-15 去对账语言：原"范围（下限）"表述已撤除（下限/落点属对账语言，会促使模型按来源逐条铺开）。
    '{material}': MATERIAL_HINT[materialChannel === 'anchor' ? 'anchor' : 'full'],
  };
  for (const [k, v] of Object.entries(map)) body = body.split(k).join(v);
  // ✅ A18：素材段段头与说明按通道渲染（模板保持通道无关；非 anchor 通道为空操作）
  body = applyMaterialChannel(body, materialChannel);
  // 3) 用户附加要求（最后，优先级最高，可覆盖前序约束）
  let extraBlock = '';
  if (extra?.trim()) extraBlock = `\n\n【用户附加要求】\n${extra.trim()}`;
  // 4) 学业质量水平（高中专属）：卷别→水平 的**唯一注入点**（单源在 config/levelMapping.js）。
  //   按学科分型（**非全科统一**）：正式卷按卷别映射——高考/等级性考试按 gaokaoLevelOf 取该科水平
  //   （数学/英语=水平二、思想政治/美术=水平三、音乐=水平二与水平三、语文/物理/化学/生物/历史/地理/信息科技=水平四），
  //   合格考按 hegeLevelOf 取该科水平（数学/英语=水平一、其余=水平二）；教辅无卷别 → 按毕业合格要求为教学基线
  //   （同 hegeLevelOf 取该科水平：数学/英语=水平一、其余=水平二，**不是**全科统一锚水平二）。
  //   非高中（义务教育无水平级）→ 空串、不注入。置于模板正文与用户附加之间（用户附加仍最后、优先级最高）。
  const levelBlock = buildLevelInstruction({ stage, subject, genType, scopeType, paperKind });
  return [taskLine, body, levelBlock, extraBlock].filter(Boolean).join('\n').trim();
}

/** 从蓝图生成卷面结构文本（**列式**，供指令注入）；参数为 findBlueprint/getExamBlueprint 返回的蓝图对象
 * 注：结构里的"题数 X"由模型按实际命制题数计（题量是命题设计结果，非程序预知值）；
 * 🔴 2026-10-06（A4 跨处一致·消相抵）：原输出"一、〈名〉(共X题，共Y分)"——**与大题标题同形**，
 *    与 cell 分值条「大题标题只写总分"（共Y分）"」两形并现（模型两见即混用，实测"整卷两种标注并存"）。
 *    现改**列式** `一、〈名〉｜题数 X｜分值 Y分`：**题数/分值作命题依据**留在结构里，
 *    **标题形态只写总分**（命题依据不充当标题模板）。
 *    分值/大题固定由蓝图确定，生成后由规则库 score 系列验算账目自洽（程序职责）。
 * 部分层（2026-09 调研对齐，docs/design/标题层级与编号规范.md）：英语蓝本大题名含"听力·/笔试·"前缀时
 *    提升为正规"第X部分 听力/笔试部分（共N大题，满分M分）"层——组行在前、大题行去前缀，
 *    大题序号全卷连续（南陵样例主流：一~九跨听力笔试连续）；语文/数学等无前缀蓝本输出形态不变。 */
export function buildStructureText(bp) {
  const sections = bp?.sections;
  if (!sections?.length) return '';
  // 2026-09-17 用户裁定（"课标里明确要求的被写在蓝本注里、而不是每一个栏目里的，要修正——确保模型知道课标的具体要求"）：
  //   蓝本 note 就是该大题的**课标/正规卷形态要求**（如"短文，选择与判断"、"每段材料读两遍"、"每空一词"），
  //   但原先以行尾 `——注` 呈现 → 模型读成**背景描述**：实证第三卷「笔试·阅读理解」注为"短文，选择与判断"，
  //   卷面却只出"判断"一种设问，且这正是它被"当描述"的直接后果。
  //   处置：每行显式标注为**要求**并附"须逐项落实"（生效方式与自查动作由【组织方式】段单源给出），
  //   使"课标要求"在**每个栏目行**上可见、可核对——不是只躺在蓝本数据里。
  const reqTag = (note) => (note ? `——【要求·须逐项落实】${note}` : '');
  const PART_RE = /^(听力|笔试)[·.](.+)$/;
  const hasPart = sections.some((s) => PART_RE.test(String(s.name || '')));
  if (!hasPart) {
    // 2026-09-27 收尾（g4）：把 sectionKindOf 接进【卷面结构】注入——"域型→大类层、题型型→直接作大题"
    //   成为注入的**给定事实**，不再由模型从栏名再猜一遍（【层级归并】条款与这里的判定同源同果）。
    //   归并判据：**相邻同性质**的栏目归并到同一个上层名；域型栏目作大类层（独立行；**序号形态按学段**——
    //   小学段大类自带序号、中学段不设大类层，见下方 2026-09-28 条；编号只用于其下的大题标题与小题目。
    //   旧"大类一律不带编号"系一刀切、已废）；题型型栏目不设大类层、块名即大题标题。
    //   大类行不携带【要求·须逐项落实】（要求标注只挂在具体大题行上，防计数测试/模型误读）。
    const kindOf = (s) => sectionKindOf(String(s.name || ''));
    // 学段（层级口径判据）：bp.stage 优先；用户自定义蓝本可能无 stage 字段 → 回退从 key（学科|学段）解析
    const stageOf = String(bp?.stage || (bp?.key ? String(bp.key).split('|')[1] : '') || '').trim();
    const domainName = (s) => {
      const n = String(s.name || '');
      const dot = n.indexOf('·');
      return dot >= 0 ? n.slice(0, dot).trim() : n.trim();
    };
    const out = [];
    let seq = 0; // 大题序号只被**真大题行**消费（域型栏目不再占用大题序号）
    for (let i = 0; i < sections.length; i++) {
      const s = sections[i];
      const kind = kindOf(s);
      // 域型（课标内容领域/板块名）：**只作大类层，不再输出同名大题行**。
      //   2026-09-28 用户报障根治：原实现在大类行之后仍输出"一、识字与写字(共X题，共40分)"——
      //  同一名称既当大类又当大题，与【卷面格式】"大类名不得充当大题标题、大题标题由模型自拟"
      //  直接冲突：模型把分值挂到大类、其下自拟的大题便无从取分值 → 大题标题无分值 →
      //  render 层 parseExamSections 认不出大题 → 注意事项/题号得分表整体不注入（预览与导出双失）。
      //  现改为：大类行自带**本大类总分**与命题要求，其下大题标题由模型按作答方式自拟、分值合计=大类总分。
      // 2026-09-28（用户裁定·按学段贴正规）：域型栏目分两种口径——
      //  · 小学段（primary_*）：作**大类（部分）层**（自带序号 + 本大类总分 + 命题要求），其下大题自拟；
      //  · 中学段（middle/high）：**不设大类层**——域型名**直接作大题标题**（真题"一、积累与运用（30分）"），
      //    落到下方大题行输出（与题型型同路径），不 continue、不出大类行。
      const primaryLevel = !isMidHighStage(stageOf);
      if (kind === 'domain' && primaryLevel) {
        const prev = sections[i - 1];
        const isGroupStart = !prev || kindOf(prev) !== 'domain' || domainName(prev) !== domainName(s);
        if (isGroupStart) {
          let sum = 0;
          const notes = [];
          for (let k = i; k < sections.length; k++) {
            if (kindOf(sections[k]) !== 'domain' || domainName(sections[k]) !== domainName(s)) break;
            sum += Number(sections[k].score) || 0;
            const nt = String(sections[k].note || '').trim();
            if (nt) notes.push(nt);
          }
          // 2026-10-04（待办A·【卷面结构】收口）：原实现把同一段"大类层口径"在**每个大类行里各写一遍**
          //   （自带序号/居中加粗/须写总分/大题自拟+不得用大类名/分值合计=总分/大题序号全卷连续），
          //   且第二个示例值**写死"（30分）"**——在 28/16/16 分的大类行里照抄 → 示例值错。
          //   现改为：**共用口径只出一次**（置于首个大类行之前；**不以"大类层："起头**，免被
          //   parseExamSections/固定件注入当作又一个大类行），各大类行只留自身信息
          //   `大类层：〈名〉（本大类共X分）[；本大类命题要求：…]`；示例值改占位 `〈本大类总分〉`。
          if (!out.some((l) => l.startsWith('· 大类层口径'))) {
            // 2026-10-04（待办A·跨块收口）：本块**只留结构职责**（大类行承载"本大类名＋本大类总分"、分值归拢）；
            //   形态（自带序号/居中加粗）、大题命名、大题序号连续**都改引用各自单源块**——
            //   原先这些在同一份实发里【卷面层级】/【大题标题命名】/【编号与组织】已各有一处正句。
            out.push(
              '· 大类层口径：大类行承载"本大类名＋本大类总分"（分值归拢）；其下**大题标题按【大题标题命名】自拟**、'
              + '各大题分值合计须等于该大类总分、**大题序号按【编号与组织】全卷连续**；大类层的呈现形态见【卷面层级】。'
            );
          }
          out.push(
            `大类层：${domainName(s)}（本大类共${sum}分）`
            + (notes.length ? `；本大类命题要求：${notes.join('；')}` : '')
          );
        }
        continue; // 域型不再占用大题序号、不输出大题行
      }
      const no = '一二三四五六七八九十'[seq] || String(seq + 1);
      seq += 1;
      const scorePart = s.score ? `｜分值 ${s.score}分` : '';
      out.push(`${no}、${s.name}｜题数 X${scorePart}${reqTag(s.note)}`);
    }
    return out.join('\n');
  }
  // 部分层：按前缀顺序分组（听力/笔试），组内大题去前缀、序号全卷连续
  // 2026-09-27（用户裁定）：部分层只写"听力部分/笔试部分"作大类居中，**不写"第X部分"字眼**
  //  （真题卷面通行：听力部分/笔试部分即部分标题，不带序；下辖大题序号仍全卷连续）
  const groups = [];
  let cur = null;
  for (const s of sections) {
    const m = PART_RE.exec(String(s.name || ''));
    if (m && (!cur || cur.part !== m[1])) {
      cur = { part: m[1], items: [] };
      groups.push(cur);
    }
    cur.items.push({ ...s, display: m ? m[2].trim() : String(s.name || '') });
  }
  const out = [];
  let seq = 0;
  for (const g of groups) {
    const sum = g.items.reduce((a, s) => a + (Number(s.score) || 0), 0);
    const partName = g.part === '听力' ? '听力部分' : '笔试部分';
    out.push(`${partName}（本部分满分${sum}分）`);
    for (const s of g.items) {
      const no = '一二三四五六七八九十'[seq] || String(seq + 1);
      seq += 1;
      const scorePart = s.score ? `｜分值 ${s.score}分` : '';
      out.push(`${no}、${s.display}｜题数 X${scorePart}${reqTag(s.note)}`);
    }
  }
  return out.join('\n');
}

