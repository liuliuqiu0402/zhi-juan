const cnOrdinal = (n) => {
  const D = '一二三四五六七八九';
  if (n <= 0) return String(n);
  if (n <= 9) return D[n - 1];
  if (n === 10) return '十';
  if (n < 20) return `十${D[n - 11]}`;
  if (n === 20) return '二十';
  return String(n);
};

