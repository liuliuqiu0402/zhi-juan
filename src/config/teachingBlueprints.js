// 🎨 栏目风格「自动轮换」计数器 —— 按次轮换（与名称池同款做法）
//    每次生成推进一格（a→b→c→d→a…）；localStorage 持久化，硬刷新/重启后接着轮换；
//    手动固定套（columnStyle 非空）完全不参与计数。
const COLUMN_STYLE_COUNTERS_KEY = 'ww_column_style_counters_v1';
let _columnStyleCounters = {};
const _columnStyleStore = () => {
  try { return typeof localStorage !== 'undefined' ? localStorage : null; } catch { return null; }
};
(function _restoreColumnStyleCounters() {
  try {
    const raw = _columnStyleStore()?.getItem(COLUMN_STYLE_COUNTERS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && typeof parsed === 'object') _columnStyleCounters = parsed;
    }
  } catch { /* ignore */ }
})();
const _persistColumnStyleCounters = () => {
  try { _columnStyleStore()?.setItem(COLUMN_STYLE_COUNTERS_KEY, JSON.stringify(_columnStyleCounters)); } catch { /* ignore */ }
};

/** 自动轮换：当前待用套（只读，不推进）——指令预览与实际生成取同一个值 */
export function peekAutoColumnStyleId(genType = '') {
  if (!COLUMN_STYLE_SETS[genType]) return 'a';
  return COLUMN_STYLE_IDS[(_columnStyleCounters[genType] || 0) % COLUMN_STYLE_IDS.length];
}

/** 自动轮换：推进一格（每次生成结束调用一次），返回推进后的待用套 */
export function advanceAutoColumnStyleId(genType = '') {
  if (!COLUMN_STYLE_SETS[genType]) return 'a';
  _columnStyleCounters[genType] = ((_columnStyleCounters[genType] || 0) + 1) % COLUMN_STYLE_IDS.length;
  _persistColumnStyleCounters();
  return peekAutoColumnStyleId(genType);
}

/** 🧪 测试专用：重置自动轮换计数器 */
export function __resetColumnStyleCounters() {
  _columnStyleCounters = {};
  _persistColumnStyleCounters();
}

/** 解析实际生效的风格套 id（''=自动轮换，非空=手动固定）
 * 手动固定：直达该套（跨稿不串套）；
 * 自动轮换：取「当前待用套」（不推进）——推进发生在一次生成结束，故预览与本次生成一致。 */
export function resolveColumnStyleId(genType = '', styleVal = '') {
  const pool = COLUMN_STYLE_SETS[genType];
  if (!pool) return 'a';
  if (styleVal && pool[styleVal]) return styleVal;
  return peekAutoColumnStyleId(genType);
}

/** 学段键归一：接受学段键（primary_low 等）或中文学段/年级标签（'小学低段'/'二年级'/'高一' 等）
 * 🔴 唯一事实源：统一委托 gradeStage.resolveStageKey（'小学低/中/高段'、一~六年级、初一~初三、高一~高三、初中/高中 全覆盖），
 *    不再本地自建启发式，杜绝三处解析互相错位的风险。 */
function normalizeTeachingStage(stage = '') {
  const s = String(stage).trim();
  if (STAGE_KEY_SET.has(s)) return s; // 五档键直接透传
  const key = resolveStageKey(s);
  return key && STAGE_KEY_SET.has(key) ? key : 'primary_mid'; // 无法识别时宽松回退（不阻断生成）
}

/**
 * 查询教辅结构蓝本（三维度：学科×类型×学段；学科专属优先，未定制回退通用默认）
 * @param {Object} opts { genType(资料类型), stage(学段键), subject(学科,可空→通用) }
 * @returns {Object|null} { label, sections, stageParams, key, custom }
 */
export function getTeachingBlueprint({ genType = '', stage = '', subject = '' } = {}) {
  // 工具库条目开关：该 学科×类型 条目（含学科定制与通用回退行）被停用 → 无教辅结构注入
  if (!isLibEntryEnabled('blueprint', `${subject || '*'}|${genType}`)) return null;
  const custom = TEACHING_SUBJECT_BLUEPRINTS[subject]?.[genType];
  const def = TEACHING_BLUEPRINTS[genType];
  const bp = custom || def;
  if (!bp) return null;
  const stageKey = normalizeTeachingStage(stage);
  // 学段要求优先级：学科级（覆盖初高中档，未覆盖档回退通用）> 类型级 custom > 通用默认
  const subjectStages = TEACHING_SUBJECT_BLUEPRINTS[subject]?.stages;
  const stages = subjectStages ? { ...(custom?.stages || def?.stages || {}), ...subjectStages } : (custom?.stages || def?.stages || {});
  const stageParams = stages[stageKey] || stages.primary_mid;
  return {
    label: bp.label, sections: bp.sections, stageParams,
    key: `${subject || '*'}|${genType}|${stageKey}`, stageKey,
    subject: subject || '*', custom: bp === custom, // 停用定制后走通用模板 → custom=false
  };
}

/**
 * 构建教辅结构注入块（供生成指令尾部附加，与 exam 的 buildStructureText 对称）
 * 只注入栏目框架 + 学段要求；题量/篇幅底线由 teaching-volume-guard 程序侧校验，不注入 prompt（防限定 AI）
 * @param {Object} opts { genType, stage, subject, columnStyle }
 * @returns {string} 空串 = 无蓝本
 */

/** 出处标注清除（2026-09 用户定版：正文不标出处）——蓝图 note 中历史遗留的"标注出处/标注教材出处/并标注出处"等
 * 措辞在注入前统一剥离，防止模型据此在正文写 出处/选自/章节名 等溯源字样；数据文案清理收敛在本单点 */
export function stripSourceMarkNote(note = '') {
  return String(note || '')
    .replace(/标注教材出处/g, '')
    .replace(/并标注出处/g, '')
    .replace(/标注出处/g, '')
    .replace(/（\s*）/g, '')
    .replace(/，{2,}/g, '，')
    .replace(/；{2,}/g, '；')
    .replace(/[，；、]\s*$/, '')
    .replace(/^\s*[，、]/, '')
    .trim();
}
export function buildTeachingInjection({ genType = '', stage = '', subject = '', columnStyle = '' } = {}) {
  const bp = getTeachingBlueprint({ genType, stage, subject });
  if (!bp) return '';
  const sections = columnStyle ? applyColumnStyle(bp.sections, genType, columnStyle) : bp.sections;
  const sectionsText = sections.map(s => `· ${s.name}——${stripSourceMarkNote(s.note)}`).join('\n');
  const p = bp.stageParams;
  const stageLine = p.note ? `\n▌学段要求（${TEACHING_STAGE_NAMES[bp.stageKey] || bp.stageKey}）\n· ${p.note}` : '';
  const cur = CURRICULUM_BY_STAGE[bp.stageKey] || CURRICULUM_BY_STAGE.primary_mid;
  // 🔴 2026-09-16（用户裁定·课标↔大类挂钩）：块头显式交代"这些大类的分类依据是课标"——
  //    原先只给栏目名，模型手上唯一的分类依据只能是教材分析的颗粒 → 颗粒被读成大题骨架。
  //    措辞零自造：只出现"大类标题"与课标版本名，不出现结构/序列/栏目框架这类词。
  return `\n\n【大类标题（下面各行即本次大类标题；按${cur}的活动类型与素养层划分；${bp.custom ? `${bp.subject}·` : ''}${bp.label}·${TEACHING_STAGE_NAMES[bp.stageKey] || bp.stageKey}）】
${sectionsText}${stageLine}`;
}

