  summary: {
    add: [{ name: '方法提炼', after: '典型例题', note: '归纳本单元可迁移的学习方法与思路' }],
    noteSuffix: { 知识框架: '，用结构图或网络图呈现知识之间的联系' },
  },
  // ⑦ 复习资料：复习目标（对标本单元学业要求，置于首栏）
  review: { add: [{ name: '复习目标', before: '知识框架', note: '对本单元学业要求，写明本次复习要达成的目标' }] },
