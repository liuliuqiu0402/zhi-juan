/** 查询某资料类型的教辅编辑知识 */
export function getTeachingMaterial(genType) {
  return TEACHING_MATERIAL_BANK[genType] || null;
}

/** 构建注入生成指令的教辅编辑知识文本 */
export function buildTeachingMaterialText(genType) {
  const t = TEACHING_MATERIAL_BANK[genType];
  if (!t) return '';
  const lines = [`【教辅编辑角色·${t.role}】`];
  lines.push(`编辑逻辑：${t.logic}`);
  lines.push('任务群导向栏目：');
  t.columns.forEach((c, i) => lines.push(`${i + 1}. ${c}`));
  lines.push('编辑铁律（新课标）：');
  t.rules.forEach((r, i) => lines.push(`${i + 1}. ${r}`));
  return lines.join('\n');
}

export default { TEACHING_MATERIAL_BANK, TEACHING_TYPES, getTeachingMaterial, buildTeachingMaterialText };
