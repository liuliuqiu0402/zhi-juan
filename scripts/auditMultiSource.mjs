// 🔍 多源巡检（**按"事务"聚类**，不按字面）
// ============================================================
// 治什么（2026-10-10 属主：历次"多源巡检"都回"没有"，可最近几轮修复**每次**都是多源（拉扯）导致的）：
//   病根在**查法**——历次用的是"同一句话出现两次"（字面去重），而真正咬人的多源是：
//     ① **两处用不同词说同一件事**（如"每个独立设问的题"↔"应编号的题"；"编号对象口径"↔"计分对象数"）；
//     ② **一处给判据、另一处给"像判据的落例"**；
//     ③ **同一要求按层级/学段切散在多处**；
//     ④ **同一事务由两个名词承载**（"题量""题数""计分对象"）。
//   ⇒ 字面法照不出 ①②③④。**改按"事务"聚类**：对每个事务，把模板里**所有**相关条款拉出来看
//      （不管用词是否相同），再判：**同一判据源**／**同源分工**／**拉扯（两处各出要求或判词）**。
// 用法：node scripts/auditMultiSource.mjs [--full]
//   默认打印每事务的**命中数与条款首段**（供人判）；`--full` 打印整条条款。
//
// 判读口径（照 `附·4·严`）：
//   · **同源分工**＝多处的对象/时机不同（如"卷面层级"管呈现、"题号与分值"管口径）。
//   · **拉扯**＝同一对象、同一时点，**两处各给要求或判词**（模型二选一 → 产出不稳）。
//   · 发现拉扯即按 `附·4` 走：一处判据＋他处只指针 → 先解后锁 → 全量绿 → 池同步 → 台账留痕。
import { getPromptTemplate } from '../src/config/promptLibrary.js';

const FULL = process.argv.includes('--full');

/** 事务表：按"事情"聚类，不按用词（用词可增补，事务不可省） */
const TOPICS = [
  ['编号/题号', /题号|编号|序号/],
  ['分值/计分', /分值|计分|单价|账目|整除|得分/],
  ['标题/命名', /标题|命名|名称|题名/],
  ['情境', /情境|背景|场景|关卡/],
  ['答案区', /答案/],
  ['重复/唯一', /重复|唯一|同义|同文|近义|同型/],
  ['层级/排版', /层级|空行|字体|加粗|居中|顶格|留白|装订|分栏|序号体系/],
  ['材料/素材', /材料|素材|原文|参考段/],
  ['数量/篇幅', /题量|数量|篇数|字数|篇幅|几题|总数/],
  ['作答位/载体', /作答位|横线|括号|方框|书写格|作答载体/],
];

const stages = ['primary_low', 'middle'];
const subjects = ['语文', '数学'];

for (const st of stages) {
  for (const sj of subjects) {
    const tpl = getPromptTemplate({ grade: st, subject: sj, genType: 'exam' }).template || '';
    const clauses = tpl.split(/\n|；/).map((s) => s.trim()).filter((s) => s.length > 6);
    console.log(`\n===== exam | ${sj} | ${st} | 条款 ${clauses.length} =====`);
    for (const [name, re] of TOPICS) {
      const hit = clauses.filter((c) => re.test(c));
      if (hit.length < 2) continue;
      console.log(`\n--[${name}] ${hit.length} 处`);
      hit.forEach((c, i) => console.log(`   ${i + 1}. ${FULL ? c : c.slice(0, 72)}`));
    }
  }
}
console.log('\n（判读：同源分工／拉扯——同一对象同一时点两处各出要求或判词即为拉扯）');
